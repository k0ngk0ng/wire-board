import type { Room } from "./types";
import { splendorRulesLabel } from "./splendor-expansions";

export function SplendorRules({ room }: { room: Room }) {
  const options = room.game?.splendor?.options ?? room.splendorOptions;
  return (
    <>
      <p>
        成为宝石商人，购买发展卡积累永久折扣和声望。2–4 人，
        {splendorRulesLabel(options)}。
      </p>
      <ol>
        <li>
          <b>每回合选择一个行动：</b>
          拿取三种不同宝石各一枚；拿取同色两枚（供应至少四枚）；购买一张公开或预留的发展卡；预留一张公开或牌堆顶牌。
        </li>
        <li>
          <b>购买：</b>
          先扣除已购卡牌的永久折扣，再支付宝石，黄金可替代任意颜色，可自行调整支付组合。
        </li>
        <li>
          <b>预留：</b>最多三张，若供应中有黄金，获得一枚。预留卡对他人保密。
        </li>
        <li>
          <b>回合收尾：</b>持有超过十枚宝石时必须归还。
          {options?.cities
            ? "城市替代贵族，不获得贵族或贵族分数。"
            : "满足贵族条件时获得一位贵族及三分，多位符合条件时自行选择。"}
        </li>
        <li>
          <b>结束：</b>
          {options?.cities
            ? "回合结束时满足任意城市的分数与发展卡张数条件，触发最后一轮。城市不被拿走，也不额外加分，多人可以达成同一城市；最后只在满足城市条件的玩家中比较分数。"
            : "任意玩家达到十五分后完成当前轮，让所有玩家行动次数相同。最高分获胜。"}
          同分时发展卡更少者获胜，仍相同则共同获胜。
        </li>
      </ol>
      {options?.cities && (
        <p>
          <b>城市条件：</b>
          按指定颜色的发展卡张数计算。“另一色”必须不同于该城市已指定的颜色；“任一色”需要一种颜色单独达到数量，不能把多种颜色相加。
        </p>
      )}
      {options?.tradingPosts && (
        <p>
          <b>贸易站：</b>
          每回合结束最多解锁一个满足发展卡条件的贸易站，多个可选时自行选择。已获得能力持续有效；购牌赠宝石与要塞征服可连续触发，最后再检查十枚上限。
        </p>
      )}
      {options?.strongholds && (
        <p>
          <b>要塞：</b>
          购买发展卡后放置或移动一座己方要塞，或移除对手单独一座要塞。对手要塞占据的卡不能购买、预留或免费取得。三座己方要塞集结后，本回合可额外支付费用征服一次。
        </p>
      )}
      {options?.orient && (
        <>
          <p>
            <b>东方牌堆：</b>
            每级额外公开两张东方卡，与基础卡使用独立牌堆。卡牌效果依次结算后再补牌。
          </p>
          <p>
            <b>永久奖励：</b>
            双宝石卡提供两枚同色折扣；复制卡与已拥有的一张有色奖励卡配对，获得其颜色和奖励数量。复制前必须已有可配对的卡。
          </p>
          <p>
            <b>免费连锁：</b>
            按牌面取得一张指定等级的公开卡，可以选择东方卡；取得后继续结算它的效果。
          </p>
          <p>
            <b>黄金卡：</b>
            购买时可弃置，每张提供两枚虚拟黄金，至少使用其中一枚；不占十枚实体筹码上限。贸易站的黄金增值同样适用，每枚黄金只能抵一种颜色。
          </p>
          <p>
            <b>弃牌购买：</b>
            弃置两张指定颜色的发展卡代替筹码支付，须优先弃置该颜色的复制卡；被弃卡的分数和永久奖励一并移除。
          </p>
          <p>
            <b>张数与折扣：</b>
            城市、贵族和贸易站条件按有色发展卡张数计算，双宝石卡仍只算一张；黄金卡和未配对的复制卡没有颜色。
          </p>
        </>
      )}
      <p>
        白色钻石、蓝色蓝宝石、绿色祖母绿、红色红宝石、黑色缟玛瑙，以及黄色黄金。
      </p>
    </>
  );
}
