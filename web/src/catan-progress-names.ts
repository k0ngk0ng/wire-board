export function catanProgressDescription(
  card: number,
  seafarers: boolean,
  explorer = false,
  pirateIslands = false,
  intro = false,
) {
  if (intro && explorer && card === 21)
    return "本站初航规则：首次蛮族进攻后可打出并归还征税；本剧本没有海盗，不产生移动或偷牌效果。";
  if (pirateIslands && card === 21)
    return "本站补充规则：首次蛮族进攻后选择一块有数字的陆地，从每位相邻建筑对手处随机偷一张资源或商品，仍遵守友善保护；不放置强盗，不移动舰队。";
  if (explorer && card === 5)
    return "将村庄升级为城市（1粮食＋2矿石）或港口（1粮食＋1矿石），先选择建筑类型，再选择地图位置。";
  if (explorer && card === 21)
    return "首次蛮族进攻后，移动探险海盗，再选择可偷取的对手；完成后返回建设阶段。";
  if (seafarers && card === 7)
    return "免费放置两条道路或船只，可混合选择，仍遵守连接和棋子库存规则。";
  if (seafarers && card === 16)
    return "移除一条开放道路或船只；自己的棋子可免费重放到同类型合法位置，对手的归还库存。船只可从海盗旁迁移，但不能切断己方骑士与建筑的连接。";
  return catanProgressDescriptions[card];
}
