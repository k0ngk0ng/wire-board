import { CatanFriendlyRobberRules } from "./catan-friendly-robber";
import { CatanHarborsRules } from "./catan-harbors";
import { CatanCitiesKnightsRules } from "./catan-cities-knights-rules";
import type { Room } from "./types";
import "./catan-rules.css";
import { catanRuleContext, type CatanRuleContext } from "./catan-rule-context";
import {
  catanLayoutName,
  catanScenarioName,
  catanScenarioVictory,
} from "./catan-scenarios";

function ScenarioRules({ info }: { info: CatanRuleContext }) {
  const { scenario, players, layout } = info;
  switch (scenario) {
    case "shores":
      return (
        <>
          <li>
            <b>从主岛出发：</b>
            两处起始建筑都必须放在主岛。每位玩家首次在每个小岛区域建村，额外获得2分；别人已定居不影响自己的奖励。
          </li>
          {players > 4 && (
            <li>
              <b>五至六人地图：</b>
              主岛随机地形、按数字螺旋布局，外围岛屿保持固定。地图蓝框内的同一区域只奖励一次，即使其中的陆地互不相连。
            </li>
          )}
        </>
      );
    case "islands":
    case "six_islands":
      return (
        <li>
          <b>自己的家乡岛：</b>
          两处起始建筑可以同岛或分处两岛，这些岛是自己的家乡岛。每位玩家首次在各个非家乡岛建村额外获得2分；家乡岛和探索奖励按玩家分别记录。
        </li>
      );
    case "fog":
      return (
        <>
          <li>
            <b>起始区域：</b>
            两处起始建筑可以放在同一座或两座已知岛上。起始建设期间发现新地形，也不能把新的地形当作起始定居区。
          </li>
          <li>
            <b>探索迷雾：</b>
            新建道路、船只或移动船只触及未知地块的交点时，揭示隐藏堆顶地形。普通资源地形放数字并奖励一张对应资源；金矿奖励自选资源；海洋和沙漠不放数字、不奖励资源。发现奖励取自银行。
          </li>
          <li>
            未探索地形和数字堆的顺序保密。本剧本没有异岛定居的额外分数；可变起始地图允许红色数字相邻。
          </li>
        </>
      );
    case "desert":
      return (
        <>
          <li>
            <b>穿越沙漠：</b>
            两处起始建筑限于沙漠带这一侧的主岛。沙漠另一侧的陆地区域和外围小岛分别是未探索区域。
          </li>
          <li>
            每位玩家首次在每个新区域建村额外得2分，不要求是全桌第一个到达。沙漠另一侧虽与主岛相连，仍单独计算区域奖励。
          </li>
        </>
      );
    case "tribe":
      return (
        <>
          <li>
            <b>接触部落：</b>
            起始和后续村庄只能建在主岛。将新船或移动的船放到带奖励的边上时立即领取，奖励从地图移走；单纯经过无奖励，不获得异岛定居分。
          </li>
          <li>
            <b>部落奖励：</b>
            胜利点立即计分；领取的发展卡视作本行动阶段新购卡，本阶段不能打出，胜利点仍可立即计入获胜。
          </li>
          <li>
            <b>带回港口：</b>
            领取港口后，在自己沿海建筑旁选择合法海岸安放，与其他港口至少隔开一条边；安放后立即可用。暂无位置时先保留，以后有位置再安放，暂存港口不提供优惠。
          </li>
        </>
      );
    case "cloth":
      return (
        <>
          <li>
            <b>三轮起始建设：</b>
            {info.citiesKnights
              ? "顺序放村庄、逆序放城市，再顺序放村庄，每座建筑配道路或船只；只有第三座村庄领取普通起始资源。"
              : "顺序、逆序、再顺序各放一组村庄与道路或船只，只从第三座村庄领取起始资源。"}
            起始建筑只能放在两座大岛，小岛村落不能定居或移动强盗过去。
          </li>
          {layout === "variable" && (
            <li>
              可变地图由先手先选择一块大岛12号地块作为强盗起点，再开始起始建设。
              {info.citiesKnights && "首次蛮族进攻前强盗保持休眠。"}
            </li>
          )}
          <li>
            <b>建立贸易：</b>
            从自己的建筑用连续船线连接到小岛村落，立即从该村落领取一枚布匹；每人每村落只建立一次关系。道路不能在空交点直接接船形成贸易线。
            {info.citiesKnights &&
              "敌方骑士阻挡新连接；已建立的关系保留。村落不能放骑士，但可以沿己方路线经过。"}
          </li>
          <li>
            <b>布匹生产：</b>
            村落数字被掷出时，与它建立贸易的玩家各领取一枚布匹。非空村落不足时从公共库存补足；已经空的村落不再生产。每两枚布匹得1分，单枚不计分；布匹不计入资源手牌弃置数量。
            {info.citiesKnights &&
              "布匹筹码与布料商品牌分开计算，不能用布匹支付城市建设。"}
          </li>
          <li>
            <b>封闭船线与海盗：</b>
            连到村落的贸易航线视为封闭，不能移走线上船只，延长分支仍按船只移动规则处理。建立至少一条贸易关系后才能移动海盗；可从相邻对手偷一张资源或一枚布匹。
          </li>
          <li>
            <b>提前结算：</b>
            自己行动中达到{info.target}
            分立即获胜。若回合结束时至少5座村落耗尽，则比较总分，同分比较布匹数量；仍相同共同获胜。配对玩家的第一段行动结束也会检查耗尽条件。
          </li>
        </>
      );
    case "pirate_islands":
      return (
        <>
          <li>
            <b>预设棋子：</b>
            每人先有一座主岛村庄和一艘船，再按顺序、逆序放两组村庄与路线。自己的西侧要塞尚未收复时不生产、不计分。本剧本没有强盗。
          </li>
          <li>
            <b>海盗巡航：</b>
            每次掷骰后、生产或处理7之前，舰队沿箭头移动较小骰点数的格数；同点取其中一颗。停在建筑旁就攻击对应玩家，海盗力量也是该骰点数。五至六人地图的“!”海格不发动攻击。
          </li>
          <li>
            <b>防守：</b>
            用自己的全部战舰数比较海盗力量。大于海盗可自选一张银行资源；相等无事发生；少于海盗随机失去“1＋自己的城市数量”张资源，最多失去现有手牌。防守结算后才处理生产或7点弃牌；7点玩家随后可以从任一有资源的对手偷一张，不移动棋子。
          </li>
          <li>
            <b>远征航线：</b>
            从自己主岛的沿海建筑出发，沿最短海路先到自己的登陆点，再到自己的要塞；远征不得分支或故意绕路阻挡他人。主岛周围仍可修建其他路线。到达登陆点后，按普通费用在那里建村。
          </li>
          <li>
            <b>战舰：</b>骑士只能将远征航线上最靠近起点的一艘普通船升级为战舰。
            {info.waiting && players === 4
              ? "三人局移除胜利点发展卡；四人局将它们作为骑士使用，不提供分数。"
              : players === 3
                ? "三人局移除胜利点发展卡。"
                : "四至六人局的胜利点发展卡也作为骑士使用，不提供分数。"}
            已用卡移出，不获得最大骑士军队。
          </li>
          <li>
            <b>攻打要塞：</b>
            远征线抵达自己的要塞后，在行动阶段结束时攻打，另掷一颗骰子。只比较这条远征线上的战舰数：大于骰点移除一层防御；相等退回末端一艘船；小于骰点退回末端两艘。攻击后结束行动。
          </li>
          <li>
            移除全部三层后，要塞恢复成自己的村庄，可生产和升级。所有要塞都被收复后移除舰队。必须收复自己的要塞，并在自己行动中达到10分才获胜。
          </li>
        </>
      );
    case "wonders":
      return (
        <>
          <li>
            <b>起始地图：</b>
            先手先选择沙漠作为强盗起点，再进行两轮起始建设。起始建筑限主岛，不可放在奇迹标记或叉号交点。本剧本没有海盗。
          </li>
          <li>
            <b>领取奇迹：</b>
            满足卡面条件后免费领取一座，领取时0级，自己独占，不能再领第二座。大桥、长城和灯塔的条件要求在对应地图标记处拥有建筑。
          </li>
          <li>
            <b>建设奇迹：</b>
            每级支付卡面所示的五份资源，最高4级；同一行动阶段可以连建多级。领取后不重复检查领取条件，等级本身不加分。每位玩家首次在每座小岛定居额外得1分。
          </li>
          <li>
            <b>获胜：</b>
            自己行动中完成4级立即获胜；或者达到{info.target}
            分，且已建奇迹等级严格领先全部对手。并列、只有{info.target}
            分或仅领取未建设都不足以获胜。
          </li>
          {players > 4 && (
            <li>五至六人使用七张奇迹卡，额外加入灯塔和大图书馆。</li>
          )}
        </>
      );
    case "new_world":
      return (
        <>
          <li>
            <b>确认地图：</b>
            地形和数字在开局前共同确认，开始后不再重抽。红色6／8不得相邻，也不能放在金矿上；强盗和海盗都从外框出发。
          </li>
          <li>
            <b>轮流放港口：</b>
            从先手开始按座位顺序，每次放当前随机抽出的港口，放在陆地与海洋或外框之间的边上，与其他港口至少隔开一条边。未来港口顺序保密。每人每次120秒，超时自动放一枚；全部放完才开始建村。
          </li>
          <li>
            <b>家乡岛：</b>
            两处起始建筑所在的一座或两座岛是自己的家乡岛。每位玩家首次在各个非家乡岛建村额外得1分，别人先到不影响自己的奖励。
          </li>
        </>
      );
    default:
      return null;
  }
}

export function CatanRules({ room }: { room: Room }) {
  const info = catanRuleContext(room);
  const { scenario, players, fiveSix, helpers } = info;
  if (info.citiesKnights)
    return (
      <>
        <CatanCitiesKnightsRules info={info} />
        {info.harbors && <CatanHarborsRules />}
        {info.friendlyRobber && <CatanFriendlyRobberRules />}
        {scenario && (
          <>
            <h4>本剧本规则</h4>
            <ol>
              <ScenarioRules info={info} />
            </ol>
          </>
        )}
      </>
    );
  const seafarers = !!scenario;
  const pirate = scenario === "pirate_islands";
  const cloth = scenario === "cloth";
  const wonders = scenario === "wonders";
  return (
    <>
      <p>
        <b>
          {seafarers
            ? `航海家 · ${catanScenarioName(scenario)}`
            : "卡坦岛基础版"}
        </b>{" "}
        · {info.waiting ? (fiveSix ? "5–6人" : "3–4人") : `${players}人`}
        {seafarers && info.layout ? ` · ${catanLayoutName(info.layout)}` : ""}。
        {catanScenarioVictory(scenario, info.target)}。
      </p>
      {info.harbors && <CatanHarborsRules />}
      {info.friendlyRobber && <CatanFriendlyRobberRules />}
      {!cloth && <p>达标获胜在自己的行动阶段判定。</p>}
      {seafarers && (
        <>
          <h4>本剧本规则</h4>
          <ol>
            <ScenarioRules info={info} />
          </ol>
        </>
      )}
      <h4>回合与建设</h4>
      <ol>
        {info.fixedBase && (
          <li>
            <b>固定新手布局：</b>
            村庄、道路、港口和数字按官方地图预放，从官方规则图中黑框标出的第二座村庄领取三张起始资源，直接由随机先手掷骰。
            {info.neutral &&
              "五人局保留未使用颜色的两座中立村庄，不放道路；中立村庄不生产、不能升级或偷取，仍阻挡相邻建村和穿越道路。"}
          </li>
        )}
        {!cloth && !info.fixedBase && (
          <li>
            <b>起始建设：</b>按顺序放一组村庄与
            {seafarers ? "道路或船只" : "道路"}
            ，再逆序放第二组。只从第二座村庄领取相邻地块各一张资源；
            {seafarers ? "金矿资源由自己选择。" : "沙漠不发资源。"}
          </li>
        )}
        <li>
          <b>生产：</b>
          回合开始掷两颗骰子，按点数向相邻村庄发一张、城市发两张资源。
          {!pirate && "强盗所在的地块不生产。"}
          {seafarers &&
            "金矿每份产出可分别选择一种银行现有资源，按提示依次领取。"}
        </li>
        {!pirate && (
          <li>
            <b>掷出7：</b>超过七张资源的玩家同时弃一半，向下取整；随后移动强盗
            {seafarers && !wonders ? "或海盗" : ""}
            ，从相邻一位有资源的对手随机偷一张。
            {seafarers &&
              !wonders &&
              "强盗对应地块旁的建筑，海盗对应海格旁的船只；海盗封锁所在海格边上造船和移动船只。"}
            {cloth && "本剧本移动海盗需要先建立村落贸易，并可改偷布匹。"}
          </li>
        )}
        <li>
          <b>交易：</b>
          掷骰结算后可按任意顺序交易和建设。银行4:1、通用港口3:1、专用港口2:1；玩家交易需双方同意，由当前玩家确认成交。
        </li>
        <li>
          <b>费用：</b>
          道路＝木材＋砖块；村庄＝木材＋砖块＋羊毛＋粮食；城市＝三矿石＋两粮食；发展卡＝羊毛＋粮食＋矿石。
          {seafarers && "船只＝木材＋羊毛。"}
        </li>
        <li>
          <b>连接与距离：</b>
          村庄必须连接己方路线，且与任何建筑至少相隔两条边；城市升级已有村庄。道路不能穿过对手建筑。
          {seafarers &&
            "道路在陆地或海岸，船只在海洋或海岸；道路与船只只在己方建筑处接续。"}
        </li>
        {seafarers && (
          <li>
            <b>移动船只：</b>
            每个行动阶段最多移动一艘开放航线末端的旧船，本阶段新造的不能移动。连接两座己方建筑的封闭航线不能拆走；移到新位置后仍须合法连接。
            {cloth && "通往贸易村落的船线同样封闭。"}
            {pirate && "海盗群岛仍须满足单线和最短航程限制。"}
          </li>
        )}
        <li>
          <b>发展卡：</b>
          每个行动阶段最多使用一张，可以在掷骰前或掷骰结算后使用；刚获得的卡在下次自己的行动阶段解锁。
          {pirate
            ? "骑士及胜利点卡按本剧本升级战舰，不提供骑士军队或隐藏分数。"
            : "胜利点不需要打出，立即计入自己的私人总分。骑士移动强盗"}
          {!pirate && (seafarers && !wonders ? "或海盗；" : "；")}
          道路建设免费造最多两条{seafarers ? "道路或船只" : "道路"}
          ，丰收选最多两张现有资源，垄断收取对手手中指定种类资源。
        </li>
        <li>
          <b>奖励：</b>
          {pirate ? (
            "本剧本不使用最长路线和最大骑士军队。"
          ) : (
            <>
              {cloth
                ? "不使用最长路线奖励。"
                : `连续路线至少5段可获得${seafarers ? "最长路线" : "最长道路"}，奖励2分。`}
              打出至少三名骑士可获得最大骑士军队，奖励2分。并列由原持有者保留，原持有者不在并列中则暂时无人持有。
            </>
          )}
        </li>
      </ol>
      {fiveSix && (
        <>
          <h4>五至六人配对回合</h4>
          <p>
            ①号玩家正常行动后，由其左侧第三位②号玩家行动：不掷骰、不与其他玩家自由交易，可以建设、使用发展卡和银行／港口交易，也可以获胜。两人各有独立120秒及一次发展卡使用机会，完成后标记向下一位移动。每位玩家新获得的发展卡在下次自己的行动阶段可用。
          </p>
        </>
      )}
      {helpers && (
        <>
          <h4>Helpers 助手</h4>
          <p>
            {info.fixedBase
              ? info.waiting
                ? "开局时每人按先手顺序领取一位初始助手"
                : "每人已按先手顺序领取一位起始助手"
              : "每人完成第二组起始建设后领取一位助手"}
            {cloth ? "，第三组建设不重发" : ""}。
            {info.allHelpers
              ? "展示全部备用助手。"
              : "本局按人数使用两倍人数的助手。"}
            点击角色查看能力与使用时机；新获得或本回合使用过的助手需要等待下一完整回合。
          </p>
          <p>
            太阳面用过后可翻到月面保留再用一次，也可换另一位；月面用过后必须交换。七点庇护等能力会改变通常的资源／弃牌处理，按角色说明结算。
            {wonders && "道路、建筑或发展卡的助手折扣不适用于奇迹费用。"}
          </p>
        </>
      )}
      <h4>计时与隐私</h4>
      <p>
        正常回合120秒。起始建设、同时弃牌、金矿和其他必要选择超时自动处理；回应时暂停原行动计时，完成后恢复剩余时间。正常回合超时后，同局其他玩家可以移出当前玩家，剩余玩家继续，最后一人获胜；房主可结束牌桌。
      </p>
      <p>
        资源手牌和发展卡种类仅本人可见，结算后公开；
        {scenario === "fog" && "未探索地形堆保持隐藏；"}
        观战者只能查看公开信息，不能操作。
      </p>
    </>
  );
}
