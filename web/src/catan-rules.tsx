        <h4>建设、生产与蛮族登陆</h4>
        <ol>
          <li>
            顺序放村庄、逆序放城市，每座建筑配道路；只从起始城市相邻资源地块各领1张资源。城堡和沙漠不生产。
          </li>
          <li>
            正常掷骰生产；7点时超过7张资源的玩家弃掉一半，然后当前玩家选择一位有资源的对手随机偷1张，不移动强盗。
