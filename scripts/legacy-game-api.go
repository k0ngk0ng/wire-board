//go:build ignore

// Regenerate the legacy API aliases after changing an existing game's public API.
// Run from the repository root: go run scripts/legacy-game-api.go
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"os"
	"path/filepath"
	"strings"
)

func main() {
	games := []string{"splendor", "rail", "catan", "carcassonne", "sanguosha"}
	var out bytes.Buffer
	fmt.Fprintln(&out, "// Code generated by scripts/legacy-game-api.go; DO NOT EDIT.\npackage game\nimport(")
	for _, g := range games {
		fmt.Fprintf(&out, "%s %q\n", g, "github.com/k0ngk0ng/wire-board/games/"+g+"/server")
	}
	fmt.Fprintln(&out, ")")
	paths, err := filepath.Glob("games/*/server/*.go")
	must(err)
	for _, path := range paths {
		if strings.HasSuffix(path, "_test.go") {
			continue
		}
		game := filepath.Base(filepath.Dir(filepath.Dir(path)))
		if !contains(games, game) {
			continue
		}
		field := strings.ToUpper(game[:1]) + game[1:]
		fs := token.NewFileSet()
		f, err := parser.ParseFile(fs, path, nil, 0)
		must(err)
		text := func(n ast.Node) string { var b bytes.Buffer; must(printer.Fprint(&b, fs, n)); return b.String() }
		for _, decl := range f.Decls {
			switch d := decl.(type) {
			case *ast.GenDecl:
				for _, spec := range d.Specs {
					switch x := spec.(type) {
					case *ast.TypeSpec:
						n := x.Name.Name
						if ast.IsExported(n) && n != "State" && n != "Action" {
							fmt.Fprintf(&out, "type %s = %s.%s\n", n, game, n)
						}
					case *ast.ValueSpec:
						for _, name := range x.Names {
							n := name.Name
							if ast.IsExported(n) {
								fmt.Fprintf(&out, "%s %s = %s.%s\n", d.Tok, n, game, n)
							}
						}
					}
				}
			case *ast.FuncDecl:
				name := d.Name.Name
				if !ast.IsExported(name) || name == "New" || name == "Apply" || name == "View" || name == "BotAction" {
					continue
				}
				args := []string{}
				for _, p := range d.Type.Params.List {
					for _, n := range p.Names {
						arg := n.Name
						if _, ok := p.Type.(*ast.Ellipsis); ok {
							arg += "..."
						}
						args = append(args, arg)
					}
				}
				callArgs := strings.Join(args, ",")
				// Print signatures via the AST function type; a FieldList alone is not a printable node.
				sig := strings.TrimPrefix(text(d.Type), "func")
				if d.Recv != nil {
					if text(d.Recv.List[0].Type) != "*State" {
						continue
					}
					fmt.Fprintf(&out, "func(s *State) %s%s {v:=s.as%s();", name, sig, field)
					if d.Type.Results == nil {
						fmt.Fprintf(&out, "v.%s(%s);s.sync%s(v)", name, callArgs, field)
					} else if len(d.Type.Results.List) == 2 && text(d.Type.Results.List[0].Type) == "Action" {
						fmt.Fprintf(&out, "a,e:=v.%s(%s);s.sync%s(v);return from%sAction(a),e", name, callArgs, field, field)
					} else {
						fmt.Fprintf(&out, "r:=v.%s(%s);s.sync%s(v);return r", name, callArgs, field)
					}
					fmt.Fprintln(&out, "}")
				} else if d.Type.Results != nil && text(d.Type.Results.List[0].Type) == "*State" {
					fmt.Fprintf(&out, "func %s%s {v,e:=%s.%s(%s);return from%s(v),e}\n", name, sig, game, name, callArgs, field)
				} else {
					fmt.Fprintf(&out, "var %s = %s.%s\n", name, game, name)
				}
			}
		}
	}
	result, err := format.Source(out.Bytes())
	must(err)
	must(os.WriteFile("internal/game/legacy_generated.go", result, 0644))
}
func contains(values []string, value string) bool {
	for _, v := range values {
		if v == value {
			return true
		}
	}
	return false
}
func must(err error) {
	if err != nil {
		panic(err)
	}
}
