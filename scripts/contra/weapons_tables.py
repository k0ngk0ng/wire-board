"""Export named weapon data tables from the verified Japanese PRG bank."""
import hashlib,json,zipfile,subprocess
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]

def main():
    with zipfile.ZipFile('/Users/jason/Documents/nes/roms/03/魂斗罗日版(完全版).zip') as archive:raw=archive.read('Contra (J).nes')
    assert hashlib.sha256(raw).hexdigest()=='6ba53139fa88b8de1ae527c438bda6f1541d1ee7df26d63dec5164a32d166bfe'
    bank=raw[16+12*8192:16+14*8192]
    read=lambda a,n:list(bank[a-0x8000:a-0x8000+n])
    word=lambda a:int.from_bytes(bytes(read(a,2)),'little')
    signed=lambda n:n-65536 if n>=32768 else n
    tables={}
    def add(name,address,count):
        values=read(address,count);tables[name]={'cpu':hex(address),'rom_offset':16+12*8192+address-0x8000,'bytes':count,'values':values,'sha256':hashlib.sha256(bytes(values)).hexdigest()};return values
    muzzle=[add(f'muzzle{i}',word(0x822c+i*2),24) for i in range(4)]
    velocities=[add(f'velocity{i}',word(0x8317+i*2),48) for i in range(6)]
    spreadY=[add(f'spreadY{i}',word(0x84dc+i*2),64) for i in range(2)]
    spreadX=[add(f'spreadX{i}',word(0x84e0+i*2),64) for i in range(2)]
    flame=add('flameCenter',0x8451,36);sounds=add('sounds',0x81e1,5);sprites=add('sprites',0x81e6,5)
    delays=add('laserDelays',0x8197,8);angle=add('spreadAngles',0x84cb,12);spreadDelta=add('spreadDelta',0x84d7,5)
    laserPose=add('laserPose',0x8651,24)
    flameX=add('flameX',0x871c,16);flameY=add('flameY',0x8718,16)
    indoorFlame=[[[*add(f'indoorFlame-{phase}-{axis}',word(0x872c+phase*4+axis*2),16)] for axis in range(2)] for phase in range(3)]
    indoorThresholds=add('indoorFlameThresholds',0x88d4,4)
    indoorSpread=add('indoorSpreadSteps',0x8913,20)
    laserX=add('laserIndoorBounds',0x8945,9);laserCodes=add('laserIndoorSprites',0x894e,9)
    def array(data):return '{'+','.join(array(x) if isinstance(x,list) else str(x) for x in data)+'}'
    code='// Code generated by scripts/contra/weapons_tables.py from named Japanese data tables; DO NOT EDIT.\npackage contra\n\n'
    pairs=[[[d[a*2],d[a*2+1]] for a in range(12)] for d in muzzle]
    speed=[[[signed(d[a*4]*256+d[a*4+1]),signed(d[a*4+2]*256+d[a*4+3])] for a in range(12)] for d in velocities]
    spread=lambda rows:[[signed(d[a*2]+256*d[a*2+1]) for a in range(32)] for d in rows]
    for name,typ,val in [('weaponMuzzles','[4][12][2]uint8',pairs),('weaponVelocities','[6][12][2]int16',speed),('spreadYVelocity','[2][32]int16',spread(spreadY)),('spreadXVelocity','[2][32]int16',spread(spreadX)),('flameOrigins','[12][3]uint8',[flame[n:n+3] for n in range(0,36,3)]),('weaponSounds','[5]uint8',sounds),('weaponSprites','[5]uint8',sprites),('laserDelays','[2][4]uint8',[delays[:4],delays[4:]]),('spreadAngles','[12]uint8',angle),('spreadDeltas','[5]uint8',spreadDelta),('laserPoses','[12][2]uint8',[laserPose[n:n+2] for n in range(0,24,2)]),('flameXOffsets','[16]uint8',flameX),('flameYOffsets','[16]uint8',flameY),('indoorFlameOffsets','[3][2][16]uint8',indoorFlame),('indoorFlameThresholds','[4]uint8',indoorThresholds),('indoorSpreadSteps','[10]int16',[signed(indoorSpread[n]+256*indoorSpread[n+1]) for n in range(0,20,2)]),('indoorLaserBounds','[9]uint8',laserX),('indoorLaserSprites','[9]uint8',laserCodes)]:code+=f'var {name} = {typ}{array(val)}\n\n'
    code=subprocess.run(['gofmt'],input=code,text=True,stdout=subprocess.PIPE,check=True).stdout
    path=ROOT/'games/contra/engine/weapons_tables.go';path.write_text(code)
    (ROOT/'docs/research/nes-contra/evidence/weapons-tables.json').write_text(json.dumps({'rom_sha256':hashlib.sha256(raw).hexdigest(),'bank8k':[12,13],'tables':tables,'output_sha256':hashlib.sha256(code.encode()).hexdigest()},indent=2)+'\n')
    print('exported',len(tables),'source-bound weapon data tables')

if __name__=='__main__':main()
