#!/usr/bin/env python3
"""Freeze a verified normalized catalogue for native-only offline perception.

Input is explicit normalized RGB/indexed pixels, never a ROM or saved World.
This regeneration tool is not called during production startup or callbacks.
"""
import argparse,base64,gzip,hashlib,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
ROM='6ba53139fa88b8de1ae527c438bda6f1541d1ee7df26d63dec5164a32d166bfe'
def digest(data):return hashlib.sha256(data).hexdigest()
def main():
 p=argparse.ArgumentParser();p.add_argument('--input',required=True);args=p.parse_args()
 source=(ROOT/args.input).resolve();assert source.is_relative_to(ROOT)
 encoded=source.read_bytes();value=json.loads(gzip.decompress(encoded));assert value['schema']==1 and value['romSHA256']==ROM
 pages=value['pages'];assert 0<len(pages)<=128 and set(pages)==set(value['catalog']['pages'])
 def asset(record,encoded,length):
  raw=base64.b64decode(encoded,validate=True);assert len(raw)==length==record['bytes'];assert digest(raw)==record['sha256']
  if length==4096:assert max(raw)<=3
  return {'bytes':length,'sha256':digest(raw)}
 # Match Go's declared struct order and encoding/json's string-key ordering.
 catalog={'rgb':asset(value['catalog']['rgb'],value['rgb'],192),'pages':{}}
 for key in sorted(pages):
  assert str(int(key))==key and 0<=int(key)<128
  catalog['pages'][key]=asset(value['catalog']['pages'][key],pages[key],4096)
 identity=digest(json.dumps(catalog,separators=(',',':')).encode())
 bundle={'schema':1,'romSHA256':ROM,'catalogID':identity,'catalog':catalog,'rgb':value['rgb'],'pages':pages}
 raw=json.dumps(bundle,sort_keys=True,separators=(',',':')).encode();assert len(raw)<1<<20
 packed=gzip.compress(raw,mtime=0);out=ROOT/'games/contra/server/data';out.mkdir(parents=True,exist_ok=True)
 (out/'visual-catalog-v1.json.gz').write_bytes(packed)
 provenance={'schema':1,'kind':'normalized indexed pixels for native offline perception','romSHA256':ROM,'source':str(source.relative_to(ROOT)),'sourceSHA256':digest(encoded),'sourceManifestSHA256':value.get('sourceManifestSHA256'),'catalogID':identity,'compressedSHA256':digest(packed),'uncompressedSHA256':digest(raw),'pages':len(pages),'bytes':len(packed),'generator':'scripts/contra/prepare_visual_bundle.py','generatorSHA256':digest(Path(__file__).read_bytes())}
 (out/'visual-source.json').write_text(json.dumps(provenance,indent=2)+'\n')
 (ROOT/'games/contra/server/production_assets_native.go').write_text('// Code generated by scripts/contra/prepare_visual_bundle.py; DO NOT EDIT.\n//go:build !js\n\npackage contra\n\nimport _ "embed"\n\n//go:embed data/visual-catalog-v1.json.gz\nvar productionVisualArchive []byte\n\nconst productionVisualArchiveSHA256 = "'+digest(packed)+'"\n')
 print(json.dumps(provenance))
if __name__=='__main__':main()
