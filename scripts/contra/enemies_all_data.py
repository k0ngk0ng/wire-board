"""Inventory Japanese per-stage enemy tables before extending runtime rules.

Failure cases: treating shared numeric kinds as equal across stages, reading
routine data past pointer boundaries, miscounting a first-pointer alias, using
first-stage spawn encoding for bases, and losing source/bank identity.
"""
from pathlib import Path
import hashlib,json,zipfile

ROOT=Path(__file__).resolve().parents[2]
ROM=Path('/Users/jason/Documents/nes/roms/03/魂斗罗日版(完全版).zip')
COUNTS=[3,17,6,17,7,5,9,7]

def read():
    archive=hashlib.sha256(ROM.read_bytes()).hexdigest()
    with zipfile.ZipFile(ROM)as z:raw=z.read('Contra (J).nes')
    assert hashlib.sha256(raw).hexdigest()=='6ba53139fa88b8de1ae527c438bda6f1541d1ee7df26d63dec5164a32d166bfe'
    return raw[16:131088],archive

def inventory():
    prg,archive=read();word=lambda at:int.from_bytes(prg[at:at+2],'little')
    stages=[];common=word(0x1edf3+16)
    for level,count in enumerate(COUNTS):
        props=word(0x1edf3+level*2);dispatch=word(0x1e5c9+level*2)
        property_rows=[]
        for kind in range(16+count):
            at=0x10000+(common if kind<16 else props)+kind*4
            property_rows.append({'kind':kind,'values':list(prg[at:at+4]),'romOffset':16+at})
        table=word(0xaa75+level*2);end=word(table);cursor=table;pointers=[]
        while cursor<end:
            if end-cursor==1:
                # The last-stage pointer table has one observed unused $FF
                # before its first stream; it is not another pointer.
                assert level==7 and prg[cursor]==0xff
                break
            target=word(cursor);assert 0x8000<=target<0xc000
            pointers.append(target);end=min(end,target);cursor+=2
        assert cursor==end or level==7 and cursor+1==end
        streams=[]
        for number,pointer in enumerate(pointers):
            at=pointer;kinds=[]
            if level in (1,3):
                if prg[at]!=255:
                    at+=1
                    while prg[at]!=255:kinds.append(prg[at+1]&63);at+=3;assert at-pointer<256
            else:
                while prg[at]!=255:kinds.append(prg[at+1]&63);at+=2+(prg[at+1]>>6)+1;assert at-pointer<256
            assert all(kind<16+count for kind in kinds)
            data=prg[pointer:at+1]
            streams.append({'screen':number,'pointer':hex(pointer),'romOffset':16+pointer,'bytes':list(data),'kinds':kinds,'sha256':hashlib.sha256(data).hexdigest()})
        stages.append({'level':level,'propertiesPointer':hex(props),'properties':property_rows,'specificDispatch':hex(dispatch),
                       'specificTables':[hex(word(0x10000+dispatch+i*2))for i in range(count)],
                       'screenTable':hex(table),'indoor':level in (1,3),'scripts':streams})
    assert [len(s['scripts'])for s in stages]==[13,6,10,9,22,13,15,11]
    return {'romSHA256':'6ba53139fa88b8de1ae527c438bda6f1541d1ee7df26d63dec5164a32d166bfe','archiveSHA256':archive,'stages':stages}

def main():
    data=inventory();out=ROOT/'docs/research/nes-contra/evidence/enemies-all-stage-data.json'
    out.write_text(json.dumps(data,indent=2)+'\n')
    import sys
    if '--export' in sys.argv:
        lines=['// Code generated by scripts/contra/enemies_all_data.py from the pinned Japanese ROM.','// Logical properties and spawn data only; no program bytes are executed.','package contra','', 'var allEnemyProperties = [8][]enemyProperties{']
        for stage in data['stages']:
            lines.append('\t{')
            for row in stage['properties']:lines.append('\t\t{%s}, // kind %02x'%(','.join(str(v)for v in row['values']),row['kind']))
            lines.append('\t},')
        lines+=['}','', 'var allEnemyScripts = [8][][]uint8{']
        for stage in data['stages']:
            lines.append('\t{')
            for row in stage['scripts']:lines.append('\t\t{%s}, // screen %d'%(','.join(str(v)for v in row['bytes']),row['screen']))
            lines.append('\t},')
        lines+=['}','']
        (ROOT/'games/contra/engine/enemies_all_tables.go').write_text('\n'.join(lines))
    print(json.dumps({'stages':8,'propertyPairs':sum(len(s['properties'])for s in data['stages']),'scripts':sum(len(s['scripts'])for s in data['stages'])}))
if __name__=='__main__':main()
