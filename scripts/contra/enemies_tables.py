"""Export source-bound first-stage enemy properties and spawn streams."""
import gzip
import hashlib
import json
from pathlib import Path
import zipfile

ROOT=Path(__file__).resolve().parents[2]

def main():
    with zipfile.ZipFile('/Users/jason/Documents/nes/roms/03/魂斗罗日版(完全版).zip')as z:r=z.read('Contra (J).nes')
    assert hashlib.sha256(r).hexdigest()=='6ba53139fa88b8de1ae527c438bda6f1541d1ee7df26d63dec5164a32d166bfe'
    p=r[16:131088]
    word=lambda at:int.from_bytes(p[at:at+2],'little')
    common,level=word(0x1edf3+16),word(0x1edf3)
    assert common==level==0xee05
    props=[list(p[0x10000+(common if kind<16 else level)+kind*4:0x10004+(common if kind<16 else level)+kind*4])for kind in range(19)]
    table=word(0xaa75);first=word(table);count=(first-table)//2
    assert count==13
    screens=[]
    for i in range(count):
        start=word(table+i*2);at=start
        while p[at]!=255:
            at+=2+((p[at+1]>>6)+1)
            assert at-start<128
        screens.append({'cpu':hex(start),'rom_offset':16+start,'bytes':list(p[start:at+1])})
    out=ROOT/'games/contra/engine'
    text='// Code generated by scripts/contra/enemies_tables.py from the pinned Japanese ROM.\n// Contains enemy data only; no executable ROM or instruction interpreter.\npackage contra\n\n'
    text+='var jungleEnemyProperties = [...]enemyProperties{\n'
    for kind,data in enumerate(props):text+='\t{%s}, // type %02x\n'%(', '.join(f'0x{x:02x}'for x in data),kind)
    text+='}\n\nvar jungleEnemyScripts = [...][]uint8{\n'
    for screen in screens:text+='\t{%s}, // %s\n'%(', '.join(f'0x{x:02x}'for x in screen['bytes']),screen['cpu'])
    text+='}\n'
    text+='\nvar soldierLevelTimers = [...]uint8{%s}\n'%(','.join(str(x)for x in p[0xaadb:0xaae3]))
    text+='var soldierSidePositions = [...]uint8{%s}\n'%(','.join(str(x)for x in p[0xaba9:0xabb9]))
    text+='// Last four attribute bytes are the original profile-7 alias into the following screen-pointer data.\n'
    text+='var soldierInitialAttributes = [...]uint8{%s}\n'%(','.join(str(x)for x in p[0xad71:0xad91]))
    text+='var soldierScreenProfiles = [...][]uint8{\n'
    ranges=[(0xad2d,0xad39),(0xad2d,0xad39),(0xad39,0xad42),(0xad2d,0xad39),(0xad42,0xad56),(0xad56,0xad62),(0xad62,0xad71),(0xad2d,0xad39)]
    for a,b in ranges:text+='\t{%s},\n'%(','.join(str(x)for x in p[a:b]))
    text+='}\n'
    (out/'enemies_tables.go').write_text(text)
    manifest={'rom_sha256':hashlib.sha256(r).hexdigest(),'property_table':'fixed:$EE05','screen_pointer_table':'bank4/5:$AD8D','properties':props,'screens':screens}
    (ROOT/'docs/research/nes-contra/evidence/enemies-tables.json').write_text(json.dumps(manifest,indent=2)+'\n')
    native=ROOT/'docs/research/nes-contra/evidence/enemies-natural.json.gz'
    d=json.loads(gzip.decompress(native.read_bytes()));d['records']=[r for r in d['records']if r['kind']in ('screenSpawn','initialize')]
    d['counts']={kind:sum(r['kind']==kind for r in d['records'])for kind in ('screenSpawn','initialize')}
    d['parent_evidence_sha256']=hashlib.sha256(native.read_bytes()).hexdigest()
    fixture=gzip.compress(json.dumps(d,separators=(',',':')).encode(),mtime=0)
    (out/'testdata/original-enemy-spawn.json.gz').write_bytes(fixture)
    steps=json.loads(gzip.decompress(native.read_bytes()))
    steps['records']=[row for row in steps['records']if row['kind']=='enemyStep']
    steps['parent_evidence_sha256']=hashlib.sha256(native.read_bytes()).hexdigest()
    (out/'testdata/original-enemy-step.json.gz').write_bytes(gzip.compress(json.dumps(steps,separators=(',',':')).encode(),mtime=0))
    print(json.dumps({'screens':len(screens),'properties':len(props),'counts':d['counts'],'fixture_sha256':hashlib.sha256(fixture).hexdigest()}))

if __name__=='__main__':main()
