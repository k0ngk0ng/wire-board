"""Extract only JP Base Boss numeric tables from the source-bound ROM."""
from pathlib import Path
import hashlib,zipfile,subprocess
ROOT=Path(__file__).resolve().parents[2]
def main():
 with zipfile.ZipFile('/Users/jason/Documents/nes/roms/03/魂斗罗日版(完全版).zip')as z:r=z.read('Contra (J).nes')
 assert hashlib.sha256(r).hexdigest()=='6ba53139fa88b8de1ae527c438bda6f1541d1ee7df26d63dec5164a32d166bfe'
 p=r[16:131088];lines=['// Code generated by scripts/contra/enemies_base_boss_tables.py from the pinned Japanese ROM.','package contra','']
 for name,address,count in [('baseEyeAttackDelays',0x8f0b,4),('baseEyeSprites',0x8f0f,8),('baseEyeProjectileFlips',0x8f8d,4),('baseGeminiSprites',0xa010,6),('baseGeminiAttackDelays',0xa016,4),('baseBubbleInitialSpeeds',0xa0ab,4),('baseBubbleSpinDelays',0xa160,4)]:
  data=p[address-0x8000:address-0x8000+count];lines.append('var '+name+' = [...]uint8{'+','.join(hex(x)for x in data)+'}')
 data=p[0xa124-0x8000:0xa160-0x8000];v=[int.from_bytes(data[i:i+2],'little',signed=True)for i in range(0,len(data),2)];lines.append('var baseBubbleVelocities = [...]int16{'+','.join(map(str,v))+'}')
 target=ROOT/'games/contra/engine/enemies_base_boss_tables.go';target.write_text('\n'.join(lines)+'\n');subprocess.run(['gofmt','-w',str(target)],check=True)
if __name__=='__main__':main()
