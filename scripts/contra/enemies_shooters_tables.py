"""Export named shooting data from the pinned Japanese ROM, not reference ASM."""
from pathlib import Path
import hashlib,json,zipfile
ROOT=Path(__file__).resolve().parents[2]

def main():
    with zipfile.ZipFile('/Users/jason/Documents/nes/roms/03/魂斗罗日版(完全版).zip')as z:r=z.read('Contra (J).nes')
    digest=hashlib.sha256(r).hexdigest();assert digest=='6ba53139fa88b8de1ae527c438bda6f1541d1ee7df26d63dec5164a32d166bfe'
    p=r[16:131088]
    ranges={'shotDirectionIndex':(0xf2e5,24),'shotComponents':(0xf2fd,14),
            'aimQuarter12':(0xf518,32),'aimQuarter24':(0xf538,32),
            'sniperInitialDelay':(0x8988,3),'sniperHideDelay':(0x898b,3),'sniperInitialFrame':(0x898e,3),
            'sniperAttackDelay':(0x89db,3),'sniperShots':(0x89de,3),
            'sniperFireFrame':(0x8ab6,3),'sniperFireY':(0x8ab9,3),'sniperFireX':(0x8abc,3),'sniperFireSpeed':(0x8abf,3),
            'turretBurstCounts':(0x842f,4),'turretRotationDelays':(0x847a,4),'turretAttackDelays':(0x847e,4),'turretFireOffsets':(0x8482,15),
            'redTurretFrames':(0x853b,11),'redTurretFireY':(0x85da,3),'redTurretFireX':(0x85dd,3),
            'bossCannonSpeed':(0x8ba1,4),'bossCannonFrames':(0x8bc8,6),
            'bossDoorOffsets':(0x8c40,17),'bossDoorFrames':(0x8c51,8),'bossDoorCollision':(0x8c59,8)}
    for n in range(2):
        a=int.from_bytes(p[0xb46+n*2:0xb48+n*2],'little')
        ranges[f'sniperSprites{n}']=(a,7)
    text='// Code generated by scripts/contra/enemies_shooters_tables.py from the pinned Japanese ROM.\npackage contra\n\n';manifest={}
    for name,(address,length) in ranges.items():
        offset=address+0x10000 if address>=0xc000 else address-0x8000
        raw=p[offset:offset+length];assert len(raw)==length
        text+=f'var {name} = [...]uint8{{'+', '.join(f'0x{v:02x}'for v in raw)+'}\n'
        manifest[name]={'cpu':hex(address),'rom_offset':offset+16,'bytes':list(raw),'sha256':hashlib.sha256(raw).hexdigest()}
    (ROOT/'games/contra/engine/enemies_shooters_tables.go').write_text(text)
    (ROOT/'docs/research/nes-contra/evidence/enemies-shooters-tables.json').write_text(json.dumps({'rom_sha256':digest,'tables':manifest},indent=2)+'\n')
    print(json.dumps({'tables':len(manifest)}))

if __name__=='__main__':main()
