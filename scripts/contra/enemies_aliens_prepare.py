"""Pin Japanese Alien's Lair state tables before native probes/implementation.

Failure inventory: regional addresses mistaken for original, shared explosion
states miscounted, same numeric kinds used across stages, unused counters
treated as random, cross-slot tentacle ownership and Boss completion collapsed.
"""
import hashlib,json
from enemies_all_data import ROOT,read

BASE=ROOT/'.local/contra-enemies-aliens'

def main():
    p,archive=read();BASE.mkdir(parents=True,exist_ok=True)
    word=lambda a:int.from_bytes(p[a:a+2],'little')
    names=['guardian','fetus','mouth','white_blob','spider','spawner','heart']
    entries=[];seeds={}
    for i,name in enumerate(names):
        table=word(0x1e657+i*2);offset=table-0x8000
        first=word(offset+2);count=(first-table-2)//2
        if i==0:
            # B463-B46F is a shared HP helper before the first B470 state.
            # Thirteen pointers end at B462, not at the first state's address.
            assert table==0xb447 and p[offset+28:offset+31].hex()=='a53120'
            count=13;seeds[0xb463]='aliens_mouth_hp'
        else:assert 1<=count<=16 and (first-table-2)%2==0
        addresses=[word(offset+state*2)for state in range(1,count+1)]
        entries.append({'kind':16+i,'name':name,'table':hex(table),'states':[hex(a)for a in addresses]})
        for state,a in enumerate(addresses,1):seeds.setdefault(a,f'aliens_{name}_{state}')
    image=p[7:0x4000]+p[0x1c000:];target=BASE/'window.bin';target.write_bytes(image)
    seed=BASE/'seeds.tsv';seed.write_text(''.join(f'{hex(a)}\tfunction\t{name}\n'for a,name in seeds.items()))
    spec={'target':str(target),'entry':'0x8007','seeds':str(seed),'output':str(BASE/'rea'),
          'addresses':[hex(a)for a in seeds],'file_sha256':hashlib.sha256(image).hexdigest(),
          'tmp':str(ROOT/'dist/contra-enemies-aliens-tmp'),'cache':str(BASE/'swift-cache')}
    (BASE/'spec.json').write_text(json.dumps(spec,indent=2)+'\n')
    (BASE/'dispatch.json').write_text(json.dumps({'archiveSHA256':archive,'entries':entries},indent=2)+'\n')
    import sys
    if '--export' in sys.argv:
        signed=lambda b:int.from_bytes(b,'big',signed=True)
        timers=list(p[0x380d:0x381a]);assert timers==[22,15,8,19,58,6,33,58,29,20,18,40,72]
        velocities=[signed(p[i:i+2])for i in range(0x3a14,0x3a50,2)]
        lines=['// Code generated by scripts/contra/enemies_aliens_prepare.py from the pinned Japanese ROM.',
               'package contra','', 'var alienAimTimers = [...]uint8{'+','.join(map(str,timers))+'}',
               'var alienVelocities = [...]int16{'+','.join(map(str,velocities))+'}',
               'var alienBlobFractionAdjust = [...]uint8{'+','.join(map(str,p[0x391d:0x393b]))+'}',
               'var alienAnimationFrames = [...]uint8{'+','.join(map(str,p[0x3a0f:0x3a14]))+'}','']
        (ROOT/'games/contra/engine/enemies_aliens_tables.go').write_text('\n'.join(lines))
    print(json.dumps({'entries':entries,'procedures':len(seeds)}))

if __name__=='__main__':main()
