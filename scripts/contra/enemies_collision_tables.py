"""Export named Japanese collision/score tables with byte-range provenance."""
from pathlib import Path
import hashlib,json,zipfile,subprocess

ROOT=Path(__file__).resolve().parents[2]
def main():
    with zipfile.ZipFile('/Users/jason/Documents/nes/roms/03/魂斗罗日版(完全版).zip')as z:r=z.read('Contra (J).nes')
    assert hashlib.sha256(r).hexdigest()=='6ba53139fa88b8de1ae527c438bda6f1541d1ee7df26d63dec5164a32d166bfe'
    p=r[16:131088];word=lambda at:int.from_bytes(p[at+0x10000:at+0x10002],'little')
    parts=[]
    def take(address,size):
        raw=p[address+0x10000:address+0x10000+size]
        parts.append({'cpu':hex(address),'romOffset':16+address+0x10000,'bytes':size,'sha256':hashlib.sha256(raw).hexdigest()})
        return list(raw)
    boxes=[take(word(0xe419+i*2),60)for i in range(5)]
    base=take(0xe3f5,20);adjust=take(0xe409,16);score=take(0xe907,10);sounds=take(0xe33d,5)
    kinds=[19,33,22,33,23,21,25,23]
    deaths=[]
    common=word(0xe911+16)
    take(0xe911,18);take(common,8)
    for level,n in enumerate(kinds):
        selected=word(0xe911+level*2);row=[]
        take(selected+8,(n-16+1)//2)
        for kind in range(n):
            address=(common if kind<16 else selected)+kind//2;value=p[address+0x10000]
            row.append((value>>(0 if kind&1 else 4))&15)
        deaths.append(row)
    text='// Code generated by scripts/contra/enemies_collision_tables.py from Japanese ROM data.\npackage contra\n\n'
    text+='var collisionBoxes = [5][15][4]uint8{\n'
    for row in boxes:
        text+='\t{'+','.join('{'+','.join(f'0x{v:02x}'for v in row[i:i+4])+'}'for i in range(0,60,4))+'},\n'
    text+='}\n'
    for name,data,width in [('collisionVariableBase',base,4),('collisionVariableAdjust',adjust,4)]:
        text+=f'var {name} = [...][4]uint8{{'+','.join('{'+','.join(f'0x{v:02x}'for v in data[i:i+4])+'}'for i in range(0,len(data),width))+'}\n'
    text+='var collisionScores = [...]uint16{'+','.join(map(str,score))+'}\n'
    text+='var collisionHitSounds = [...]uint8{'+','.join(f'0x{v:02x}'for v in sounds)+'}\n'
    text+='var collisionDeathRoutine = [8][]uint8{\n'+''.join('\t{'+','.join(map(str,row))+'},\n'for row in deaths)+'}\n'
    out=ROOT/'games/contra/engine/enemies_collision_tables.go';out.write_text(text)
    subprocess.run(['gofmt','-w',str(out)],check=True)
    (ROOT/'docs/research/nes-contra/evidence/enemies-collision-tables.json').write_text(json.dumps({'romSHA256':hashlib.sha256(r).hexdigest(),'tables':parts,'deathPointerTable':'0xe911','deathRoutines':deaths,'outputSHA256':hashlib.sha256(out.read_bytes()).hexdigest()},indent=2)+'\n')

if __name__=='__main__':main()
