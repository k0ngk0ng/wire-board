"""Project all retained original team-AI calls and source-bound strategy tables."""
import csv
import argparse
import hashlib
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[2]


def main(write_go=False):
    run=ROOT/'.local/nes-basket/runs/team-ai-shot-observation'
    rows=list(csv.DictReader((run/'team-ai.csv').open()))
    raw=(run/'team-ai-ram.bin').read_bytes()
    assert len(raw)==len(rows)*4096 and len(rows)==1197
    def decode(r):
        def position(i):
            return dict(x=r[0x68+i]+256*r[0x75+i]+65536*r[0x82+i],depth=r[0x8f+i]+256*r[0x9c+i],height=r[0xa9+i]+256*r[0xb6+i]+65536*r[0xc3+i])
        return dict(teamModes=list(r[0x663:0x665]),teamCounters=list(r[0x668:0x66a]),
            modes=list(r[0x672:0x676]),plans=list(r[0x676:0x67a]),
            counters=list(r[0x66e:0x672]),targets=list(r[0x67a:0x67e]),destinations=list(r[0x67e:0x682]),parameters=list(r[0x682:0x686]),
            teams=list(r[0x586:0x588]),hasHuman=[(r[0x539+i]&r[0x53a+i]&128)==0 for i in (0,2)],
            humanTactics=list(r[0x666:0x668]),humanCommands=[r[0x653],r[0x655]],humanStatus=[r[0x658],r[0x65a]],
            holder=r[0x53f],previousHolder=r[0x546],scoreDifference=r[0x696],court=r[0x58b],
            objects=[position(i) for i in range(7)],airborne=[bool(r[0x5f7+i]&128) for i in range(4)],attachments=list(r[0x642:0x646]),
            hoops=[dict(position=position(i),action=r[0x512+i],owner=r[0x539+i]) for i in range(7,13)],random=list(r[0x48:0x4c]))
    records=[dict(frame=int(row['frame']),branches=[int(row['team0_branch']),int(row['team1_branch'])],
                  before=decode(raw[i*4096:i*4096+2048]),after=decode(raw[i*4096+2048:(i+1)*4096])) for i,row in enumerate(rows)]
    out=ROOT/'games/basketball/engine/testdata'
    target=out/'ai-team.json';target.write_text(json.dumps(records,separators=(',',':'))+'\n')
    target.with_name('ai-team-source.json').write_text(json.dumps(dict(source_is_original_execution=True,records=len(rows),trace_sha256=hashlib.sha256(raw).hexdigest(),sha256=hashlib.sha256(target.read_bytes()).hexdigest(),source=json.loads((run/'source.json').read_text())),indent=2)+'\n')
    rom=(ROOT/'.local/nes-basket/basketball.nes').read_bytes();bank=rom[16+5*16384:16+6*16384]
    r=lambda a:bank[a-0x8000]
    w=lambda a:r(a)+256*r(a+1)
    tables=dict(computer=[[[r(w(w(0x967e+2*t)+2*s)+i) for i in range(6)] for s in range(7)] for t in range(8)],
                human=[[r(w(0x9467+2*t)+i) for i in range(4)] for t in range(6)],
                computerModes=[r(0xa04b+i) for i in range(16)],humanModes=[r(0xa03b+i) for i in range(16)])
    (out/'ai-team-profiles.json').write_text(json.dumps(tables,indent=2)+'\n')
    (out/'ai-team-profiles-source.json').write_text(json.dumps(dict(source='Original bank 5 strategy data, $9467/$967E/$A03B/$A04B',rom_sha256=hashlib.sha256(rom).hexdigest(),sha256=hashlib.sha256((out/'ai-team-profiles.json').read_bytes()).hexdigest()),indent=2)+'\n')
    if write_go:
        def literal(value):
            if isinstance(value,list):return '{'+','.join(literal(item) for item in value)+'}'
            return str(value)
        declarations=[('originalTeamComputerPlans','[8][7][6]AIMode','computer'),('originalTeamHumanPlans','[6][4]AIMode','human'),('originalComputerTeamModes','[16]uint8','computerModes'),('originalHumanTeamModes','[16]uint8','humanModes')]
        source='// Code generated by scripts/basketball/extract_ai_team.py --write-go; DO NOT EDIT.\n// Original strategy data from bank 5; no runtime ROM access.\npackage engine\n\n'
        source+='\n'.join(f'var {name} = {kind}{literal(tables[key])}\n' for name,kind,key in declarations)
        (ROOT/'games/basketball/engine/ai_team_profiles.go').write_text(source)
    print('ai-team',len(records))


if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--write-go',action='store_true')
    main(parser.parse_args().write_go)
