"""Source-data seed export; CPU oracle verifies result presets before generation.
Failure inventory: engine/runtime_presentation_display_test.go.
No captured RAM/frames in production; court history is supplied by live runtime.
"""
import argparse,gzip,json,hashlib,subprocess
from pathlib import Path
from static_sprites import SpriteROM,DIGEST
from static_court import court_tile_layers,initial_court_ring,stream_court_column
from result_art import decode_background
from verify_postresult_assets import background_oracle
ROOT=Path(__file__).resolve().parents[2]
def main():
 p=argparse.ArgumentParser();p.add_argument('--generate-code',action='store_true');a=p.parse_args()
 rom=SpriteROM((ROOT/'.local/nes-basket/basketball.nes').read_bytes())
 presets={i:decode_background(rom,i) for i in [99,*range(101,109)]}
 for i,row in presets.items():
  source=background_oracle(rom,i)
  assert row['target']==source['target'] and row['data']==source['data']
 rows=[];digits=[[1,2,3],[4,5,6]];bases=list(rom.prg[4*16384+0x3d82:4*16384+0x3d8c])
 for court in range(8):
  ring=initial_court_ring(rom,court)
  columns=[dict(column=c,phase=1) for c in [52,2,39,17,29,60]]
  for c in columns:stream_court_column(rom,ring,c['column'],c['phase'],court)
  patches=[dict(plane=0,row=6,column=8,tiles=[31,32]),dict(plane=1,row=14,column=12,tiles=[67])]
  for q in patches:ring['tiles'][q['plane']][q['row']*32+q['column']:q['row']*32+q['column']+len(q['tiles'])]=q['tiles']
  tables=[ring['tiles'][i]+ring['attributes'][i] for i in range(2)]
  for preset in [99,court+101]:
   row=presets[preset];table=(row['target']-8192)//2048;at=(row['target']-8192)%1024
   tables[table][at:at+len(row['data'])]=row['data']
  for side,score in enumerate(digits):
   for col,digit in enumerate(score):
    for y in range(3):
     at=(1+y)*32+8+side*10+col*2;tables[0][at:at+2]=[bases[digit]+y*16,bases[digit]+y*16+1]
  rows.append(dict(Court=court,Columns=columns,Patches=patches,Digits=digits,Surface=dict(nametables=tables,palette=[15]*32,mirroring=1)))
 raw=json.dumps(rows,separators=(',',':')).encode();target=ROOT/'games/basketball/engine/testdata/postresult-runtime-seed.json.gz'
 target.write_bytes(gzip.compress(raw,mtime=0))
 report=dict(rom_sha256=DIGEST,fixture_sha256=hashlib.sha256(raw).hexdigest(),source='CPU executed DC15..DC96 result presets99/101..108; bank1 800C/801C court rows/attributes, BC74/BCFF retained stream composition; bank4 BD82 digit tiles',cases=len(rows),limitation='Static source/semantic court history; not earned whole-console result capture')
 (target.parent/'postresult-runtime-seed-source.json').write_text(json.dumps(report,indent=2)+'\n')
 if a.generate_code:
  lines=['// Code generated by generate_postresult_runtime_seed.py from ROM '+DIGEST+'; DO NOT EDIT.','package engine','var originalRuntimeResultBackground = [8][1024]uint8{']
  for court in range(8):lines.append('{'+','.join(map(str,presets[court+101]['data']))+'},')
  lines+=['}','var originalRuntimeResultHUD = [192]uint8{'+','.join(map(str,presets[99]['data']))+'}','var originalRuntimeResultDigits = [10]uint8{'+','.join(map(str,bases))+'}','var originalRuntimeCourtTiles = [8][2][30][64]uint8{']
  for court in range(8):
   layers=court_tile_layers(rom,court);lines.append('{')
   for layer in layers:lines.append('{'+','.join('{'+','.join(map(str,row))+'}' for row in layer['tiles'])+'},')
   lines.append('},')
  lines+=['}','var originalRuntimeCourtAttributes = [8][2][2][64]uint8{']
  for court in range(8):
   layers=court_tile_layers(rom,court);lines.append('{'+','.join('{'+','.join('{'+','.join(map(str,row))+'}' for row in layer['attributes'])+'}' for layer in layers)+'},')
  lines+=['}'];generated=ROOT/'games/basketball/engine/postresult_seed_assets_generated.go';generated.write_text('\n'.join(lines)+'\n')
  subprocess.run(['gofmt','-w',str(generated)],check=True)
 print(json.dumps(report))
if __name__=='__main__':main()
