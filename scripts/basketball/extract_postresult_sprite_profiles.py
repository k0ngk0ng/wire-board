"""Generate original post-result source pieces/head tables, never fixture data."""
import argparse,hashlib,json
from pathlib import Path
from static_sprites import SpriteROM,DIGEST
from postresult_art import actor_profiles
ROOT=Path(__file__).resolve().parents[2]
def main():
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
 rom=SpriteROM((ROOT/'.local/nes-basket/basketball.nes').read_bytes())
 lines=['// Code generated by scripts/basketball/extract_postresult_sprite_profiles.py; DO NOT EDIT.','// Original ROM SHA256: '+DIGEST,'// Profile pointers bank2:8000; kind19 table fixed:C410. Heads fixed:D12D.','package engine','','var originalPostResultSpriteProfiles = [3][][]postResultSpritePiece{']
 pieces=0;poses=0
 for kind in [17,18,19]:
  lines.append('{')
  for pose in actor_profiles(rom,kind):
   lines.append('{'+','.join('{%d,%d,%d,%d}'%(x['tile'],x['attributes'],x['x'],x['y']+23) for x in pose)+'},');poses+=1;pieces+=len(pose)
  lines.append('},')
 lines.append('}');lines.append('var originalPostResultHeadOffsets = [4][13]uint8{')
 for tile in range(4):lines.append('{'+','.join(str(rom.read(rom.word(0xd12d+tile*2)+i)) for i in range(13))+'},')
 lines.append('}');payload=('\n'.join(lines)+'\n').encode()
 file=ROOT/'games/basketball/engine/postresult_sprite_profiles_generated.go'
 if args.check:
  import subprocess
  payload=subprocess.run(['gofmt'],input=payload,capture_output=True,check=True).stdout
  assert file.read_bytes()==payload
 else:file.write_bytes(payload)
 report=dict(romSHA256=DIGEST,kinds=[17,18,19],poses=poses,pieces=pieces,headOffsets=52,source='D079/D0C6 profiles; D12D/D135/D13F/D149 head tables; character+scene offset')
 if not args.check:(ROOT/'.local/postresult-surface-source/sprite-profile-source.json').write_text(json.dumps(report,indent=2)+'\n')
 print(json.dumps(report))
if __name__=='__main__':main()
