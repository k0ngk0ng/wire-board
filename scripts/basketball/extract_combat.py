"""Project complete contact responses and original attack-response data."""
import argparse
import csv
import hashlib
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[2]


def main(write_go=False):
    run=ROOT/'.local/nes-basket/runs/combat-shot-observation'
    def state(r):
        def word(a,b):return r[a]+256*r[b]
        def body(i):
            fields=dict(action=0x512,request=0x51f,pose=0x5b,facing=0x46b,clock=0x437,cursor=0x444,repeatCount=0x451,nextAction=0x52c,air=0x5f7,attachment=0x642,heading=0x4ec,passage=0x6d7,variant=0x57a,attackGrade=0x625,resistance=0x611)
            result={name:r[base+i] for name,base in fields.items()}
            result.update(x=word(0x68+i,0x75+i)+65536*r[0x82+i],depth=word(0x8f+i,0x9c+i),height=word(0xa9+i,0xb6+i)+65536*r[0xc3+i],vx=word(0x478+i,0x485+i),vy=word(0x492+i,0x49f+i),vz=word(0x4ac+i,0x4b9+i),gravity=word(0x4c6+i,0x4d3+i))
            return result
        return dict(players=[body(i) for i in range(4)],candidates=list(r[0x3c:0x42]),court=r[0x58b],holder=r[0x53f],previousHolder=r[0x546],lastTouch=r[0x6a8],hoopOwners=list(r[0x540:0x546]),ballAction=r[0x518],ballRequest=r[0x525],random=list(r[0x48:0x4c]),ai=list(r[0x66a:0x686]))
    out=ROOT/'games/basketball/engine/testdata'
    for kind,count in [('phase',1197),('call',9)]:
        rows=list(csv.DictReader((run/f'combat-{kind}s.csv').open()));raw=(run/f'combat-{kind}-ram.bin').read_bytes()
        assert len(rows)==count and len(raw)==count*4096
        records=[]
        for i,row in enumerate(rows):
            item=dict(frame=int(row['frame']),before=state(raw[i*4096:i*4096+2048]),after=state(raw[i*4096+2048:(i+1)*4096]))
            if kind=='phase':item['sounds']=[int(x) for x in row['sounds'].split(';') if x]
            else:item.update(source=int(row['source']),target=int(row['target']))
            records.append(item)
        p=out/f'combat-{kind}s.json';p.write_text(json.dumps(records,separators=(',',':'))+'\n')
        p.with_name(f'combat-{kind}s-source.json').write_text(json.dumps(dict(source_is_original_execution=True,records=count,trace_sha256=hashlib.sha256(raw).hexdigest(),sha256=hashlib.sha256(p.read_bytes()).hexdigest(),source=json.loads((run/'source.json').read_text())),indent=2)+'\n')
        print(kind,count)
    rom=(ROOT/'.local/nes-basket/basketball.nes').read_bytes();b=rom[16+5*16384:16+6*16384];r=lambda a:b[a-0x8000]
    tables=dict(profiles=[[r(0x93b8+i*6+j) for j in range(6)] for i in range(12)],variants=[r(0x9400+i) for i in range(103)],resistanceDamage=[r(0x8889+i) for i in range(7)],depthPushCourts=[bool(r(0x886b+i)) for i in range(8)])
    p=out/'combat-profiles.json';p.write_text(json.dumps(tables,indent=2)+'\n')
    p.with_name('combat-profiles-source.json').write_text(json.dumps(dict(source='Original bank 5 $93B8/$9400/$8889/$886B',rom_sha256=hashlib.sha256(rom).hexdigest(),sha256=hashlib.sha256(p.read_bytes()).hexdigest()),indent=2)+'\n')
    if write_go:
        def literal(value):
            if isinstance(value,list):return '{'+','.join(literal(v) for v in value)+'}'
            if isinstance(value,bool):return str(value).lower()
            return str(value)
        source='// Code generated by scripts/basketball/extract_combat.py --write-go; DO NOT EDIT.\n// Original combat data; no runtime ROM access.\npackage engine\n\n'
        for name,kind,key in [('originalCombatProfiles','[12][6]uint8','profiles'),('originalCombatVariants','[103]uint8','variants'),('originalEnduranceDamage','[7]uint8','resistanceDamage'),('originalCombatDepthPush','[8]bool','depthPushCourts')]:source+=f'var {name} = {kind}{literal(tables[key])}\n'
        (ROOT/'games/basketball/engine/combat_profiles.go').write_text(source)


if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--write-go',action='store_true');main(p.parse_args().write_go)
