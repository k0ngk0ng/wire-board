"""Export original role/attack selection and frame data as static semantic Go data."""
from pathlib import Path
import hashlib,json
ROOT=Path(__file__).resolve().parents[2]
r=(ROOT/'.local/basketball/rea/owned-ball/bank6-visible.bin').read_bytes()
def word(a):return int.from_bytes(r[a-0x8000:a-0x8000+2],'little')
lines=['// Code generated by scripts/basketball/extract_attack_profiles.py; DO NOT EDIT.','package engine','','type originalAttackProfile struct { Variant, Handler uint8 }','var originalAttackProfiles = [9][32]originalAttackProfile{']
variants=set()
for a in range(9):
 ptr=word(0xa022+a*2);pairs=[r[ptr-0x8000+i*2:ptr-0x8000+i*2+2] for i in range(32)];variants.update(v for v,h in pairs)
 lines.append('{'+','.join('{%d,%d}'%(v,h) for v,h in pairs)+'},')
lines+=['}','var originalAttackSounds = [9][32]uint8{']
for a in range(9):
 ptr=word(0xa2d8+a*2);lines.append('{'+','.join(str(b) for b in r[ptr-0x8000:ptr-0x8000+32])+'},')
lines+=['}','var originalAttackAnimations = map[uint8]AnimationSpec{']
for v in sorted(variants):
 ptr=word(0xac8f+2*v);at=ptr;frames=[]
 while r[at-0x8000]<253:
  p,t=r[at-0x8000:at-0x8000+2];assert t>0
  frames.append('{Pose:Pose{Frame:%d,Mirrored:%s},Ticks:%d}'%(p&127,'true' if p&128 else 'false',t));at+=2;assert len(frames)<128
 marker=r[at-0x8000];ending={255:'RepeatForever',254:'RepeatRemaining',253:'RepeatUntilCount'}[marker]
 limit=r[at-0x8000+1] if marker==253 else 0
 lines.append('%d:{Frames:[]AnimationFrame{%s},End:%s,RepeatLimit:%d},'%(v,','.join(frames),ending,limit))
lines+=['}']
(ROOT/'games/basketball/engine/attack_profiles.go').write_text('\n'.join(lines)+'\n')
(ROOT/'.local/basketball/rea/player-attack/profile-source.json').write_text(json.dumps(dict(source_sha256=hashlib.sha256(r).hexdigest(),selection_address='bank6:a022',animation_address='bank6:ac8f',sound_address='bank6:a2d8',roles=32,actions=9,variants=len(variants)),indent=2)+'\n')
print('exported',len(variants),'variant animations')
