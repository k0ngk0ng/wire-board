await writeFile(path.join(temporary, 'index.html'), `<script>addEventListener('error',event=>document.documentElement.dataset.fixtureError=event.message);addEventListener('unhandledrejection',event=>document.documentElement.dataset.fixtureError=String(event.reason))</script><script type="module" src="/@fs/${path.join(root, 'games/cs16/tests/combat-effects-fixture.ts')}"></script>`);
