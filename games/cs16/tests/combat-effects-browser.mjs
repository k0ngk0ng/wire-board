const baseline = process.env.CS16_COMBAT_BASELINE === '1' ? (await execute('git', ['rev-parse', 'HEAD'], { cwd: root, env })).stdout.trim() : undefined;
const baselineSources = new Map();
if (baseline) for (const file of ['games/cs16/web/renderer.ts', 'games/cs16/web/shot-effects.ts']) baselineSources.set(path.join(root, file), (await execute('git', ['show', baseline + ':' + file], { cwd: root, env })).stdout);
