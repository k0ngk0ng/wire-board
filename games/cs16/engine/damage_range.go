func exponentialRangeDamage(damage, modifier, distance int) int {
	if damage <= 0 {
		return 0
	}
	if distance <= 0 || modifier >= 1000 {
		return damage
	}
	logarithm := damageRangeLogarithm(modifier)
	if logarithm == 0 || damage >= len(damageLogarithms) {
		return 0
	}
	lower, upper := 0, damage
	for lower < upper {
		target := (lower + upper + 1) / 2
		high, low := bits.Mul64(damageLogarithms[damage]-damageLogarithms[target], 500*Unit)
		boundary, _ := bits.Div64(high, low, logarithm)
		if uint64(distance) <= boundary {
			lower = target
		} else {
			upper = target - 1
		}
	}
	return lower
}

func penetrationDamage(damage, modifier int) int {
	if modifier == 450 {
		return damage * 7549747 / 16777216
	}
	return damage * modifier / 1000
}
