import test from "node:test";
import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { mkdir, rm } from "node:fs/promises";
import { fileURLToPath, pathToFileURL } from "node:url";
import path from "node:path";
import source from "../web/art.json" with {type:"json"};
const root=fileURLToPath(new URL("../../../",import.meta.url));
const temporary=path.join(root,".local/stoneage/resident-assets/temporary");
await mkdir(temporary,{recursive:true});
const require=createRequire(new URL("../../../web/package.json",import.meta.url));
await require("esbuild").build({entryPoints:[path.join(root,"games/stoneage/web/assets.ts")],outfile:path.join(temporary,"assets.mjs"),bundle:true,format:"esm",define:{"import.meta.env":"{}"},legalComments:"none"});
const assets=await import(pathToFileURL(path.join(temporary,"assets.mjs")));
await rm(temporary,{recursive:true,force:true});
const view={phase:"selection",pool:{pets:[{graphic:100000}],rides:[{graphic:100005,riders:[{avatar:100010,graphic:100015}]}],hats:[],weapons:[],clothes:[],accessories:[]},players:[]};
test("selection prepares the future battle animations of all selectable candidates",()=>{
 const files=assets.matchResources(view),urls=new Set(files.map(file=>file.url));
 for(const graphic of [100000,100005])for(const action of source.sprites[graphic]??[])for(const frame of action.frames)assert.ok(urls.has(assets.assetURL(frame.file)),frame.file);
 assert.ok(urls.has(assets.assetURL("battle/battle_00.png")));
 assert.equal(files.filter(file=>file.url.endsWith('.wav')).length,3);
 assert.ok(files.every(file=>file.bytes>0));
 assert.equal(files.length,urls.size);
});
