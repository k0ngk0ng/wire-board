// ResolvePlayerRequest restores fixed E18B before the selected player handler.
// The E208 table uses one rejection bit per current action; entered status
// never participates in its index. A rejected request remains pending.
func ResolvePlayerRequest(original Player) (Player, error) {
	if !original.Request.Pending {
		return original, nil
	}
	if original.Action >= 106 || original.Request.Action >= 106 {
		return original, fmt.Errorf("player request %x -> %x outside original action table", original.Action, original.Request.Action)
	}
	if originalPlayerRequestRejections[original.Request.Action][original.Action/8]&(128>>(original.Action%8)) != 0 {
		return original, nil
	}
	result := original
	result.Action, result.Entered, result.Request.Pending = result.Request.Action, false, false
	return result, nil
}

