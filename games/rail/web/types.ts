import type { GameHeader, RoomBase } from "../../../web/src/types";
export type RailMapSpec = {
  id: string;
  name: string;
  minPlayers: number;
  maxPlayers: number;
  width: number;
  height: number;
  trains: number;
  doubleMin: number;
  setupTickets: number;
  longTickets: boolean;
  initialReturn: boolean;
  additionalReturn: boolean;
  wildSingle: boolean;
  wildRule: string;
  bonus: string;
  stations: number;
  art: string;
  rules: string[];
};
export type RailPayment = { color: number; tokens: number[] };
export type Ticket = {
  art?: number;
  long?: boolean;
  options?: { to: number; points: number }[];
  value?: number;
  mandala?: boolean;
  id: number;
  a: number;
  b: number;
  points: number;
  complete: boolean;
};
export type RailPlayer = {
  stations?: number[];
  stationRoutes?: number[];
  stationScore?: number;
  mandalaCount?: number;
  mandalaScore?: number;
  network?: number;
  mountainTrains?: number;
  mountainRoutes?: number;
  eliminated?: boolean;
  hand?: number[];
  handCount: number;
  tickets?: Ticket[];
  ticketCount: number;
  trains: number;
  score: number;
  routeScore: number;
  ticketScore: number;
  longest: number;
  bonus: number;
  completed?: number;
};
export type City = {
  kind?: string;
  country?: string;
  id: number;
  name: string;
  x: number;
  y: number;
  label?: number[];
};
export type Route = {
  tunnel?: boolean;
  ferry?: number;
  mountain?: number;
  substitute?: number;
  id: number;
  a: number;
  b: number;
  length: number;
  color: number;
  segments?: { x: number; y: number; angle: number }[];
};
export type Catalog = {
  map: RailMapSpec;
  cities: City[];
  routes: Route[];
  tickets: Ticket[];
};
export type RailState = {
  map?: string;
  mapInfo: RailMapSpec;
  payments?: Record<string, RailPayment[]>;
  tunnel?: {
    route: number;
    color: number;
    base: number[];
    revealed: number[];
    extra: number;
    wildOnly: boolean;
  };
  drawId?: number;
  drawEvents?: { id: number; player: number; slot: number; color?: number }[];
  hiddenDrawId?: number;
  hiddenDrawEvents?: { id: number; player: number }[];
  face: number[];
  faceVersion?: number[];
  players: RailPlayer[];
  owners: Record<string, number>;
  pending?: Ticket[];
  setup: boolean;
  setupReady?: boolean[];
  drawn: number;
  lastRemaining: number;
  ticketsRemaining: number;
  remaining: number;
};
export type RoomOptions = { railMap?: string };
export type Game = GameHeader & { rail?: RailState };
export type Room = RoomBase & RoomOptions & { game?: Game };
