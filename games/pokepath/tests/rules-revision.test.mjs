import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { mkdir, readFile, rm, symlink, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import test from "node:test";
import { generateRulesRevision } from "../build/rules-revision.mjs";

const root = fileURLToPath(new URL("../../../", import.meta.url));
const evidence = path.join(root, ".local/pokepath/verification/rules-revision");
const digest = (bytes) => createHash("sha256").update(bytes).digest("hex");

test("源码、事实和客户端规则摘要可重建且拒绝过期产物", async () => {
  const fixture = path.join(evidence, "fixture");
  await rm(fixture, { force: true, recursive: true });
  const engine = path.join(fixture, "games/pokepath/engine");
  const data = path.join(fixture, "games/pokepath/data");
  const publicRoot = path.join(fixture, "games/pokepath/assets/public/pokepath/v1");
  await mkdir(engine, { recursive: true });
  await mkdir(data, { recursive: true });
  await mkdir(path.join(publicRoot, "routes"), { recursive: true });
  await writeFile(path.join(engine, "a.go"), "package engine\nfunc A() int { return 1 }\n");
  await writeFile(path.join(engine, "resources.go"), "package engine\nconst Resource = `facts`\n");
  await writeFile(path.join(engine, "a_test.go"), "package engine\nfunc IgnoreTest() {}\n");
  await writeFile(path.join(data, "catalog.json"), `${JSON.stringify({ version: "1.7.3", source: { sourceSha256: "a".repeat(64) } })}\n`);
  const core = Buffer.from('{"version":"1.7.3"}\n');
  const route = Buffer.from('{"id":0}\n');
  await writeFile(path.join(publicRoot, "catalog.json"), core);
  await writeFile(path.join(publicRoot, "routes/0.json"), route);
  await writeFile(path.join(publicRoot, "resources.json"), `${JSON.stringify({ version: "1.7.3", files: [{ path: "catalog.json", bytes: core.length, sha256: digest(core), mime: "application/json" }, { path: "routes/0.json", bytes: route.length, sha256: digest(route), mime: "application/json" }], aliases: { "logical.wav": "actual.flac" } })}\n`);
  const first = await generateRulesRevision({ root: fixture });
  assert.match(first.rulesRevision, /^[a-f0-9]{64}$/);
  assert.equal(first.engine.files.length, 2);
  assert.equal(first.engine.files.some((file) => /_test\.go$|rules_revision\.go$/.test(file.path)), false);
  assert.equal(first.clientData.files.length, 2);
  const generatedPath = path.join(engine, "rules_revision.go");
  const generated = await readFile(generatedPath);
  assert.match(generated.toString(), /func RulesVersion\(\) string/);
  assert.match(generated.toString(), new RegExp(first.rulesRevision));
  const manifestPath = path.join(publicRoot, "rules-revision.json");
  const bytes = await readFile(manifestPath);
  const index = JSON.parse(await readFile(path.join(publicRoot, "resources.json"), "utf8"));
  assert.deepEqual(index.aliases, { "logical.wav": "actual.flac" });
  assert.ok(index.files.some((file) => file.path === "rules-revision.json" && file.bytes === bytes.length && file.sha256 === digest(bytes)));
  assert.equal(first.clientData.files.some((file) => file.path === "rules-revision.json" || file.path === "resources.json"), false);
  assert.deepEqual(await generateRulesRevision({ root: fixture, check: true }), first);
  await writeFile(path.join(engine, "a.go"), "package engine\n\nfunc A()int{return 1}\n");
  await writeFile(path.join(engine, "a_test.go"), "package engine\nfunc IgnoreDifferentTest() {}\n");
  assert.equal((await generateRulesRevision({ root: fixture, check: true })).rulesRevision, first.rulesRevision);
  await writeFile(generatedPath, Buffer.concat([generated, Buffer.from("\nconst UnauthorizedRevision = true\n")]));
  await assert.rejects(generateRulesRevision({ root: fixture, check: true }), /stale|revision|generated/i);
  await generateRulesRevision({ root: fixture });
  await writeFile(path.join(engine, "a.go"), "package engine\nfunc A() int { return 2 }\n");
  await assert.rejects(generateRulesRevision({ root: fixture, check: true }), /stale|revision|generated/i);
  const changed = await generateRulesRevision({ root: fixture });
  assert.notEqual(changed.rulesRevision, first.rulesRevision);
  assert.equal(changed.clientData.sha256, first.clientData.sha256);
  await writeFile(path.join(publicRoot, "routes/0.json"), '{"id":0,"changed":true}\n');
  await assert.rejects(generateRulesRevision({ root: fixture, check: true }), /stale|revision|generated/i);
  const clientChanged = await generateRulesRevision({ root: fixture });
  assert.equal(clientChanged.rulesRevision, changed.rulesRevision);
  assert.notEqual(clientChanged.clientData.sha256, changed.clientData.sha256);
  const stable = await readFile(manifestPath);
  await generateRulesRevision({ root: fixture });
  assert.deepEqual(await readFile(manifestPath), stable);
  await assert.rejects(generateRulesRevision({ root: path.resolve(root, "..") }), /outside|workspace/i);
  const localManifest = path.join(data, "rules-revision.json");
  const localBytes = await readFile(localManifest);
  await rm(localManifest);
  await symlink("/etc/hosts", localManifest);
  await assert.rejects(generateRulesRevision({ root: fixture, check: true }), /outside|symlink/i);
  await rm(localManifest);
  await writeFile(localManifest, localBytes);
  await mkdir(evidence, { recursive: true });
  await writeFile(path.join(evidence, "result.json"), `${JSON.stringify({ command: "node --test games/pokepath/tests/rules-revision.test.mjs", passed: true, first, changed, clientChanged }, null, 2)}\n`);
});
