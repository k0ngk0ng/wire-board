import test from "node:test";
import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { mkdir } from "node:fs/promises";
const require = createRequire(new URL("../../../web/package.json", import.meta.url));
const directory = new URL("../../../.local/pokepath/native-ui-test/", import.meta.url);
await mkdir(directory, { recursive: true });
const target = new URL("world-animations.mjs", directory);
await require("esbuild").build({ entryPoints: [new URL("../web/world-animations.ts", import.meta.url).pathname], outfile: target.pathname, bundle: true, format: "esm", platform: "node" });
const { createWorldAnimations, updateWorldAnimations } = await import(target.href);
const view = (clock, events = [], zones = [], epoch = 1) => ({ epoch, route: 0, clock, physicsClock: clock, events, world: { zones } });
const blast = (id, at) => ({ id, at, type: "shadowTagExplosion", x: 100, y: 200, amount: 60 });
test("shadow explosions never replay history and survive event eviction until the 450ms physics deadline", () => {
  const state = createWorldAnimations();
  updateWorldAnimations(state, view(100, [blast(1, 90)]));
  assert.equal(state.explosions.length, 0);
  updateWorldAnimations(state, view(200, [blast(1, 90), blast(2, 200)]));
  assert.equal(state.explosions.length, 1);
  assert.equal(state.explosions[0].radius, 60);
  updateWorldAnimations(state, view(200, []));
  assert.equal(state.explosions.length, 1);
  updateWorldAnimations(state, view(649));
  assert.equal(state.explosions.length, 1);
  updateWorldAnimations(state, view(650));
  assert.equal(state.explosions.length, 0);
  updateWorldAnimations(state, view(700, [blast(3, 700)]));
  updateWorldAnimations(state, view(700, [blast(3, 700)]), true);
  assert.equal(state.explosions.length, 0);
});
test("singularity emits exactly one observed waiting-to-pulling flash and none after reset or resume", () => {
  const state = createWorldAnimations();
  const waiting = { id: 11, kind: "singularity", phase: "waiting", ageMS: 980 };
  const pulling = { ...waiting, phase: "pulling", ageMS: 0 };
  updateWorldAnimations(state, view(980, [], [waiting]));
  assert.equal(state.flashes.size, 0);
  updateWorldAnimations(state, view(1000, [], [pulling]));
  assert.deepEqual([...state.flashes], [11]);
  updateWorldAnimations(state, view(1000, [], [pulling]));
  assert.equal(state.flashes.size, 0);
  updateWorldAnimations(state, view(1000, [], [waiting]));
  updateWorldAnimations(state, view(1000, [], [pulling]), true);
  assert.equal(state.flashes.size, 0);
  updateWorldAnimations(state, view(1000, [], [waiting]));
  updateWorldAnimations(state, view(1000, [], [pulling], 2));
  assert.equal(state.flashes.size, 0);
});
