import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { join } from "node:path";
const root = fileURLToPath(new URL("../../../", import.meta.url));
const url = process.argv[2] ?? "http://127.0.0.1:8792/board.html";
if (!["localhost", "127.0.0.1"].includes(new URL(url).hostname)) throw Error("An independent local Board fixture is required");
const output = join(root, ".local/pokepath/verification/board-input");
mkdirSync(output, { recursive: true });
const environment = { ...process.env, TMPDIR: join(root, ".local/tmp"), AGENT_BROWSER_SOCKET_DIR: join(root, ".local/ab"), AGENT_BROWSER_PROFILE: join(root, ".local/pokepath/classic-fixture/input-profile"), AGENT_BROWSER_ARGS: "--mute-audio,--disable-breakpad,--disable-crash-reporter", AGENT_BROWSER_SCREENSHOT_DIR: output, AGENT_BROWSER_NO_VERSION_CHECK: "1" };
const session = execFileSync("agent-browser", ["session", "id", "--scope", "worktree", "--prefix", "ppinput"], { cwd: root, env: environment, encoding: "utf8" }).trim();
const browser = (...args) => { const result = JSON.parse(execFileSync("agent-browser", ["--session", session, ...args, "--json"], { cwd: root, env: environment, encoding: "utf8", timeout: 45000 })); if (!result.success) throw Error(JSON.stringify(result)); return result.data; };
const evaluate = source => browser("eval", "-b", Buffer.from(source).toString("base64")).result;
const report = { command: `node games/pokepath/tests/input-board-ui.mjs ${url}`, muted: true, passed: false, checks: [], screenshots: [] };
const check = (name, value) => { assert.equal(value, true, name); report.checks.push(name); };
try {
  browser("open", url);
  browser("set", "viewport", "1238", "674");
  browser("reload");
  browser("wait", "--load", "load");
  browser("wait", "--fn", "document.documentElement.dataset.ready==='true'");
  browser("focus", "canvas");
  browser("press", "q");
  check("Q opens the profile through the production Board", evaluate("Boolean(document.querySelector('.pokepath-classic-profile'))"));
  browser("press", "Escape");
  browser("focus", "canvas");
  browser("press", "Control+1");
  check("Ctrl+1 saves with no accidental deployment", evaluate("window.boardFixture.actions.at(-1).type==='saveTeam'&&window.boardFixture.actions.at(-1).slot===0"));
  browser("press", "F1");
  check("F1 loads the same formation", evaluate("window.boardFixture.actions.at(-1).type==='loadTeam'&&window.boardFixture.actions.at(-1).slot===0"));
  browser("press", "w");
  browser("wait", "--fn", "Boolean(document.querySelector('.pokepath-classic-routes'))");
  check("entering routes submits one authoritative mapOpen", evaluate("window.boardFixture.actions.filter(action=>action.type==='mapOpen').length===1"));
  browser("click", ".pokepath-classic-routes>nav>button:first-child");
  check("route layout changes do not reroll map visibility", evaluate("window.boardFixture.actions.filter(action=>action.type==='mapOpen').length===1"));
  browser("focus", "canvas"); browser("press", "Escape");
  browser("wait", "--fn", "!document.querySelector('.pokepath-classic-routes')");
  browser("press", "w");
  browser("wait", "--fn", "Boolean(document.querySelector('.pokepath-classic-routes'))&&window.boardFixture.actions.filter(action=>action.type==='mapOpen').length>=2");
  check("reopening routes submits exactly one new mapOpen", evaluate("window.boardFixture.actions.filter(action=>action.type==='mapOpen').length===2"));
  browser("focus", "canvas"); browser("press", "Escape");
  browser("press", "s");
  browser("wait", "--fn", "Boolean(document.querySelector('.pokepath-classic-shop'))");
  browser("press", "z");
  browser("wait", "--fn", "Boolean(document.querySelector('.pokepath-damage-monitor'))");
  check("Z chart leaves the shop open", evaluate("Boolean(document.querySelector('.pokepath-classic-shop')&&document.querySelector('.pokepath-damage-monitor'))"));
  const geometry = evaluate("document.querySelector('.pokepath-damage-rows').getBoundingClientRect().toJSON()");
  assert.deepEqual([geometry.x, geometry.y, geometry.width, geometry.height], [979, 37, 259, 462]);
  const before = evaluate("window.boardFixture.actions.length");
  browser("click", ".pokepath-damage-mode");
  check("damage mode toggles locally without a rule action", evaluate(`document.querySelector('[data-damage-mode=overdamage]')!==null&&window.boardFixture.actions.length===${before}`));
  const screenshot = join(output, "shop-damage.png");
  browser("screenshot", screenshot); report.screenshots.push(screenshot);
  browser("focus", "canvas"); browser("press", "Escape");
  browser("press", "x");
  check("X keyboard accepted without issuing a room action", evaluate(`window.boardFixture.actions.length===${before}`));
  browser("press", "q");
  browser("fill", ".pokepath-profile-player input", "s");
  check("typing S stays in profile", evaluate("Boolean(document.querySelector('.pokepath-classic-profile'))&&!document.querySelector('.pokepath-classic-shop')"));
  browser("focus", "canvas"); browser("press", "Escape");
  evaluate("window.boardFixture.actions.length=0;window.boardFixture.sounds.length=0");
  browser("mouse", "move", "700", "400");
  browser("wait", "--fn", "window.boardFixture.actions.some(action=>action.type==='aim')");
  check("mouse aim uses stable owned identity and absolute map coordinates", evaluate("(()=>{const action=window.boardFixture.actions.find(action=>action.type==='aim');return action.pokemonID===917&&Math.abs(action.x-441)<1&&Math.abs(action.y-375)<1})()"));
  report.mouseAim = evaluate("window.boardFixture.actions.filter(action=>action.type==='aim')");
  check("continuous pointer aim does not emit UI click audio", evaluate("window.boardFixture.sounds.length===0"));
  browser("click", '[data-classic-section="profile"]');
  evaluate("window.boardFixture.actions.length=0");
  browser("mouse", "move", "710", "410");
  check("central dialogs stop pointer commands", evaluate("window.boardFixture.actions.length===0"));
  browser("focus", "canvas"); browser("press", "Escape");
  evaluate("document.querySelector('#root').setAttribute('data-controller-navigation','pokepath');window.boardFixture.actions.length=0");
  browser("press", "s");
  check("mapped controllers disable the old hardcoded S shortcut", evaluate("!document.querySelector('.pokepath-classic-shop')"));
  evaluate("window.boardFixture.navigate('shop')");
  check("public controller action opens shop", evaluate("Boolean(document.querySelector('.pokepath-classic-shop'))"));
  evaluate("window.boardFixture.navigate('cancel')");
  check("public cancel closes the current panel", evaluate("!document.querySelector('.pokepath-classic-shop')"));
  browser("focus", "canvas");
  evaluate("window.boardFixture.navigate('select1')");
  evaluate("window.boardFixture.navigate('navRight')");
  const cursor = evaluate("({x:Number(document.querySelector('canvas').dataset.controllerX),y:Number(document.querySelector('canvas').dataset.controllerY)})");
  check("controller direction owns a finite logical map cursor", Number.isFinite(cursor.x) && Number.isFinite(cursor.y));
  evaluate("window.boardFixture.navigate('navRight')");
  check("controller cursor moves by one 24px map cell", evaluate(`Number(document.querySelector('canvas').dataset.controllerX)===${cursor.x + 24}`));
  evaluate("window.boardFixture.navigate('cancel')");
  browser("focus", "canvas");
  const controllerTarget = evaluate("(()=>{const view=window.boardFixture.state();return view.towers.find(tower=>tower.pokemonID===73)})()");
  evaluate("window.boardFixture.navigate('select1')");
  evaluate("window.boardFixture.navigate('navRight')");
  let currentCursor = evaluate("({x:Number(document.querySelector('canvas').dataset.controllerX),y:Number(document.querySelector('canvas').dataset.controllerY)})");
  const destination = { x: 396, y: 468 };
  for (const [axis, positive, negative] of [["x", "navRight", "navLeft"], ["y", "navDown", "navUp"]]) {
    const steps = Math.round((destination[axis] - currentCursor[axis]) / 24);
    for (let index = 0; index < Math.abs(steps); index++) evaluate(`window.boardFixture.navigate('${steps > 0 ? positive : negative}')`);
  }
  evaluate("window.boardFixture.navigate('confirm')");
  check("controller confirm deploys the selected stable identity at its logical cursor", evaluate("window.boardFixture.actions.at(-1)?.type==='deploy'&&window.boardFixture.actions.at(-1)?.pokemonID===73&&window.boardFixture.actions.at(-1)?.tileID===16"));
  report.controllerDeployment = evaluate("window.boardFixture.actions.at(-1)");
  evaluate("window.boardFixture.navigate('confirm')");
  check("controller confirm starts a wave when no deployment is pending", evaluate("window.boardFixture.actions.at(-1)?.type==='wave'"));
  browser("click", ".pokepath-classic-controls .pause");
  browser("click", ".pokepath-classic-controls .pause");
  browser("set", "viewport", "320", "674");
  browser("focus", "canvas"); browser("press", "Escape");
  check("mobile layout has no horizontal document overflow", evaluate("document.documentElement.scrollWidth<=innerWidth"));
  browser("focus", "canvas");
  evaluate("window.boardFixture.navigate('select0')");
  evaluate("window.boardFixture.navigate('cancel')");
  const touchPoint = evaluate("(()=>{const camera=document.querySelector('.pokepath-camera').getBoundingClientRect(),canvas=document.querySelector('canvas'),rect=canvas.getBoundingClientRect(),x=camera.left+200,y=camera.top+180;return{x,y,mapX:(x-rect.left)*canvas.width/rect.width,mapY:(y-rect.top)*canvas.height/rect.height}})()");
  const endpoint = browser("get", "cdp-url").cdpUrl;
  const touch = mode => execFileSync(process.execPath, [join(root, "scripts/browser_touch.mjs"), endpoint, url, mode, String(touchPoint.x), String(touchPoint.y), String(touchPoint.x + 48), String(touchPoint.y + 32)], { cwd: root, env: environment, timeout: 30000 });
  evaluate("window.boardFixture.actions.length=0");
  touch("tap");
  check("real mobile tap immediately aims the selected stable flying partner", evaluate(`(()=>{const action=window.boardFixture.actions.at(-1);return action?.type==='aim'&&action.pokemonID===917&&Math.abs(action.x-${touchPoint.mapX})<1&&Math.abs(action.y-${touchPoint.mapY})<1})()`));
  report.touchAim = evaluate("window.boardFixture.actions.filter(action=>action.type==='aim')");
  for (const mode of ["drag", "pinch", "cancel"]) {
    evaluate("window.boardFixture.actions.length=0");
    touch(mode);
    check(`real mobile ${mode} emits no map aim`, evaluate("window.boardFixture.actions.length===0"));
  }
  const mobile = join(output, "mobile-input.png"); browser("screenshot", mobile); report.screenshots.push(mobile);
  report.trace = evaluate("window.boardFixture.actions");
  report.passed = true;
} finally { writeFileSync(join(output, "result.json"), JSON.stringify(report, null, 2) + "\n"); }
process.stdout.write(JSON.stringify(report) + "\n");
