export type Side = "plants" | "zombies";
export type PlantKind = string;
export type ZombieKind = string;
export type Scene = "day" | "night" | "pool" | "fog" | "roof" | "roofnight";
export type MapSpec = { id: Scene; rows: number; cols: number; night: boolean; waterRows: number[]; roof: boolean; fog: boolean };
export type Layer = "support" | "body" | "shell" | "instant";
export type Options = {
  mode: "duel" | "team";
  teams: number[];
  roundSeconds: number;
  prepSeconds: number;
  scene: Scene;
};
export type Spec = {
  kind: string;
  name: string;
  cost: number;
  cooldown?: number;
  cooldownTicks?: number;
  hp?: number;
  description?: string;
  originalId?: number;
  target?: "cell" | "row" | "plant" | "area";
  layer?: Layer;
  upgradeFrom?: string;
  waterOnly?: boolean;
  roofOnly?: boolean;
  scenes?: string[];
};
export type Player = {
  team: number;
  side: Side;
  money: number;
  cooldowns: Record<string, number>;
  seq: number;
  deck: string[];
  imitaterKind: string;
};
export type Plant = {
  id: number;
  owner: number;
  kind: PlantKind;
  row: number;
  col: number;
  hp: number;
  maxHP: number;
  readyAt: number;
  bornAt?: number;
  attackAt?: number;
  burstAt?: number;
  layer?: Layer;
  asleep?: boolean;
  state?: string;
  targetKind?: string;
  imitated?: boolean;
  uses?: number;
  targetId?: number;
  effectUntil?: number;
  chargeMS?: number;
  flags?: Record<string, number>;
};
export type Zombie = {
  id: number;
  owner: number;
  kind: ZombieKind;
  row: number;
  x: number;
  hp: number;
  maxHP: number;
  armor?: number;
  maxArmor?: number;
  slowUntil?: number;
  state?: string;
  bornAt?: number;
  vaulted?: boolean;
  vaultUntil?: number;
  allegiance?: string;
  altitude?: number;
  diving?: boolean;
  digging?: boolean;
  targetId?: number;
  abilityMS?: number;
  abilityUntil?: number;
  flags?: Record<string, number>;
};
export type Projectile = { id: number; row: number; x: number; kind: string; y?: number; vx?: number; vy?: number; targetX?: number; targetY?: number; landAt?: number; height?: number; radius?: number; pierce?: number; payload?: string; targetId?: number };
export type Mower = { row: number; state: "ready" | "moving" | "spent"; x: number };
export type Event = { id: number; type: string; tick: number; row?: number; x?: number; col?: number; kind?: string; owner?: number; target?: number };
export type RoundResult = { attackTeam: number; breached: boolean; elapsedMS: number };
export type View = {
  protocol: number;
  options: Options;
  map: MapSpec;
  epoch: string;
  round: number;
  phase: "prepare" | "battle" | "intermission" | "finished";
  tick: number;
  serverAt: number;
  phaseUntil: number;
  players: Player[];
  plants: Plant[];
  zombies: Zombie[];
  projectiles: Projectile[];
  mowers: Mower[];
  events: Event[];
  rounds: RoundResult[];
  canAct: boolean;
  catalog: { plants: Spec[]; zombies: Spec[] };
  snapshot?: unknown;
  digest?: string;
  frames?: unknown[];
  winnerTeam?: number;
  wireMode?: "replay" | "projection";
  projection?: boolean;
  visibility?: { cells: (boolean | number)[][] };
  graves?: { id?: number; row: number; col: number; hp?: number }[];
  ladders?: { id?: number; row: number; col: number }[];
  pickups?: { id: number; row: number; x: number; y: number; kind: string; owner: number; amount: number; autoAt: number; expiresAt: number }[];
  craters?: { id: number; row: number; col: number; until: number }[];
  terrain?: { id: number; row: number; fromX: number; toX: number; owner: number; kind: string; until: number }[];
  fogClearedUntil?: number;
};
