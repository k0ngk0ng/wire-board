export type Side = "plants" | "zombies";
export type PlantKind = "sunflower" | "peashooter" | "repeater" | "snowpea" | "wallnut" | "potatomine" | "cherrybomb" | "tallnut";
export type ZombieKind = "zombie" | "conehead" | "buckethead" | "newspaper" | "polevaulter" | "football";
export type Options = {
  mode: "duel" | "team";
  teams: number[];
  roundSeconds: number;
  prepSeconds: number;
};
export type Spec = {
  kind: string;
  name: string;
  cost: number;
  cooldown?: number;
  cooldownTicks?: number;
  hp?: number;
  description?: string;
};
export type Player = {
  team: number;
  side: Side;
  money: number;
  cooldowns: Record<string, number>;
  seq: number;
};
export type Plant = {
  id: number;
  owner: number;
  kind: PlantKind;
  row: number;
  col: number;
  hp: number;
  maxHP: number;
  readyAt: number;
  bornAt?: number;
  attackAt?: number;
  burstAt?: number;
};
export type Zombie = {
  id: number;
  owner: number;
  kind: ZombieKind;
  row: number;
  x: number;
  hp: number;
  maxHP: number;
  armor?: number;
  maxArmor?: number;
  slowUntil?: number;
  state?: string;
  bornAt?: number;
  vaulted?: boolean;
  vaultUntil?: number;
};
export type Projectile = { id: number; row: number; x: number; kind: string };
export type Mower = { row: number; state: "ready" | "moving" | "spent"; x: number };
export type Event = { id: number; type: string; tick: number; row?: number; x?: number; col?: number; kind?: string; owner?: number; target?: number };
export type RoundResult = { attackTeam: number; breached: boolean; elapsedMS: number };
export type View = {
  protocol: number;
  options: Options;
  epoch: string;
  round: number;
  phase: "prepare" | "battle" | "intermission" | "finished";
  tick: number;
  serverAt: number;
  phaseUntil: number;
  players: Player[];
  plants: Plant[];
  zombies: Zombie[];
  projectiles: Projectile[];
  mowers: Mower[];
  events: Event[];
  rounds: RoundResult[];
  canAct: boolean;
  catalog: { plants: Spec[]; zombies: Spec[] };
  snapshot?: unknown;
  digest?: string;
  frames?: unknown[];
  winnerTeam?: number;
};
export type PvzAction = {
  type: "plant" | "spawn" | "shovel";
  epoch: string;
  seq: number;
  kind?: string;
  row?: number;
  col?: number;
  plantId?: number;
};
